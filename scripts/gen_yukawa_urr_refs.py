"""Regenerate crates/ferric-integrals/tests/data/yukawa_urr_ref.rs (issue #443).

Usage: python3 scripts/gen_yukawa_urr_refs.py crates/ferric-integrals/tests/data/yukawa_urr_ref.rs
Needs mpmath. 50-digit quadrature of the defining Yukawa core integral.
"""
import mpmath as mp, math, sys
mp.mp.dps = 50


def ref(m, T, U):
    T = mp.mpf(T)
    U = mp.mpf(U)

    def f(t):
        if t == 0:
            return mp.mpf(0)
        return t ** (2 * m) * mp.exp(U * (1 - t ** -2) - T * t * t)

    s = mp.sqrt(U)
    pts = [mp.mpf(0)] + [s * k for k in (0.01, 0.1, 1, 10, 100, 1000, 1e4) if s * k < 1] + [mp.mpf(1)]
    return mp.quad(f, pts, maxdegree=10)


# U = 0 is unreachable (the shim rejects zeta <= 0); 1e-30 stands in for it.
Us = [1e-30, 1e-14, 1e-9, 9e-8]
Ts = [1e-8, 1e-6, 1e-3, 0.1, 1.0, 3.0, 5.0, 10.0, 20.0]
MM = 36
out = []
for U0 in Us:
    z = 2 * math.sqrt(U0)
    U = 0.25 * z * z
    for T in Ts:
        vals = [ref(m, T, U) for m in range(MM + 1)]
        out.append((z, T, U, vals))
with open(sys.argv[1], "w") as f:
    f.write("// Generated by mpmath (50 digits, mp.quad of the defining integral\n")
    f.write("// G_m = int_0^1 t^2m exp(U(1 - t^-2) - T t^2) dt with breakpoints at sqrt(U)*{.01..1e4}).\n")
    f.write("// Rows: (zeta, T, U = 0.25*zeta*zeta, G_0..G_36), one_over_rho = 1.\n")
    f.write("pub const REF: &[(f64, f64, f64, [f64; 37])] = &[\n")
    for z, T, U, v in out:
        f.write("    (%r, %r, %r, [\n" % (z, T, U))
        for i in range(0, 37, 3):
            f.write("        " + ", ".join(mp.nstr(x, 21) for x in v[i : i + 3]) + ",\n")
        f.write("    ]),\n")
    f.write("];\n")
