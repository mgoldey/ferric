"""Regenerate crates/ferric-integrals/tests/data/yukawa_urr_ref.rs (issue #443).

Usage: uv run --no-sync --with mpmath python scripts/gen_yukawa_urr_refs.py \
    crates/ferric-integrals/tests/data/yukawa_urr_ref.rs
then `rustfmt --edition 2021` that file: the committed data file is generator
output piped through rustfmt.
Needs mpmath. 50-digit working precision; the stock rows (REF_STOCK) are good to
~3e-15 absolute worst case (see the comment in ref()).
"""

import mpmath as mp
import math
import sys

mp.mp.dps = 50


def ref(m, T, U, peak=False):
    T = mp.mpf(T)
    U = mp.mpf(U)

    def f(t):
        if t == 0:
            return mp.mpf(0)
        return t ** (2 * m) * mp.exp(U * (1 - t**-2) - T * t * t)

    s = mp.sqrt(U)
    pts = (
        [mp.mpf(0)]
        + [s * k for k in (0.01, 0.1, 1, 10, 100, 1000, 1e4) if s * k < 1]
        + [mp.mpf(1)]
    )
    if peak:
        # Large-T integrands are narrow (peak at t = sqrt(m/T)) and a coarse
        # panel set silently loses 1e-4..1e-8 relative at T = 1000 (checked
        # against the perturbative series): use 80 uniform panels to 8 peaks.
        c = mp.sqrt(mp.mpf(max(m, 1)) / T)
        top = min(mp.mpf(1), 8 * c)
        pts = sorted(set(pts + [top * i / 80 for i in range(81)]))
    if peak:
        # tanh-sinh with these panels is only good to ~1e-12 relative at
        # T = 1000 (its error estimate is useless there); Gauss-Legendre on
        # the same panels agrees with the perturbative series to <=4e-21 relative for
        # 2603 of the 2640 stock values; the other 37 (T = 1000, m = 17-20, worst
        # 2.64e-15 at m = 20; T = 240, m = 36 at 1.35e-18) are off by that much.
        # Worst case ~3e-15, ~4000x below the test's bars. Cause not chased.
        return mp.quad(f, pts, method="gauss-legendre", maxdegree=6)
    return mp.quad(f, pts, maxdegree=10)


# U = 0 is unreachable (the shim rejects zeta <= 0); 1e-30 stands in for it.
Us = [1e-30, 1e-14, 1e-9, 9e-8]
Ts = [1e-8, 1e-6, 1e-3, 0.1, 1.0, 3.0, 5.0, 10.0, 20.0]
MM = 36
out = []
for U0 in Us:
    z = 2 * math.sqrt(U0)
    U = 0.25 * z * z
    for T in Ts:
        vals = [ref(m, T, U) for m in range(MM + 1)]
        out.append((z, T, U, vals))
with open(sys.argv[1], "w") as f:
    f.write("// Generated by mpmath (50 digits, mp.quad of the defining integral\n")
    f.write(
        "// G_m = int_0^1 t^2m exp(U(1 - t^-2) - T t^2) dt with breakpoints at sqrt(U)*{.01..1e4}).\n"
    )
    f.write("// Rows: (zeta, T, U = 0.25*zeta*zeta, G_0..G_36), one_over_rho = 1.\n")
    f.write("pub const REF: &[(f64, f64, f64, [f64; 37])] = &[\n")
    for z, T, U, v in out:
        f.write("    (%r, %r, %r, [\n" % (z, T, U))
        for i in range(0, 37, 3):
            f.write(
                "        " + ", ".join(mp.nstr(x, 21) for x in v[i : i + 3]) + ",\n"
            )
        f.write("    ]),\n")
    f.write("];\n")

# U >= Umin (interpolation-table region), m <= 20 (the 2.7.2 table limit).
TUs = [1.5e-7, 1e-3, 0.5, 20.0]
TTs = [0.0, 1e-8, 1e-3, 0.5, 2.0, 10.0]
TM = 20
rows = []
for U0 in TUs:
    z = 2 * math.sqrt(U0)
    U = 0.25 * z * z
    for T in TTs:
        rows.append((z, T, U, [ref(m, T, U) for m in range(TM + 1)]))
with open(sys.argv[1], "a") as f:
    f.write(
        "\n// Interpolation-table region (U >= Umin = 1e-7): rows (zeta, T, U, G_0..G_20).\n"
    )
    f.write("pub const REF_TABLE: &[(f64, f64, f64, [f64; 21])] = &[\n")
    for z, T, U, v in rows:
        f.write("    (%r, %r, %r, [\n" % (z, T, U))
        for i in range(0, 21, 3):
            f.write(
                "        " + ", ".join(mp.nstr(x, 21) for x in v[i : i + 3]) + ",\n"
            )
        f.write("    ]),\n")
    f.write("];\n")

# Stock region (U < Umin, T >= the override threshold): the part of the Yukawa
# dispatch the override leaves on libint's own recursion. The in-Rust gating test
# compares it only to a port of that recursion; these rows are an independent
# truth anchor out to T = 1000, plus a band just BELOW the threshold (0.7-0.95x)
# that the quadrature fallback must serve (a lowered threshold hands it to the
# recursion). Rows: (zeta, T, U, mmax, G_0..G_mmax).
SMs = [1, 6, 12, 20, 36]
SUs = [1e-14, 1e-9, 9e-8]
rows = []
for mm in SMs:
    ts = 0.5 * mm + 6.0
    Tl = sorted(
        {
            ts * 0.7,
            ts * 0.85,
            ts * 0.95,
            ts,
            ts * 1.05,
            ts * 1.5,
            ts * 3,
            ts * 10,
            50.0,
            200.0,
            1000.0,
        }
    )
    for U0 in SUs:
        z = 2 * math.sqrt(U0)
        U = 0.25 * z * z
        for T in Tl:
            rows.append((z, T, U, mm, [ref(m, T, U, peak=True) for m in range(mm + 1)]))
with open(sys.argv[1], "a") as f:
    f.write(
        "\n// Stock region (U < Umin, T from 0.7x to 1000 around the 0.5 mmax + 6 threshold): rows (zeta, T, U, mmax, G_0..G_mmax).\n"
    )
    f.write("pub const REF_STOCK: &[(f64, f64, f64, usize, &[f64])] = &[\n")
    for z, T, U, mm, v in rows:
        f.write("    (%r, %r, %r, %d, &[\n" % (z, T, U, mm))
        for i in range(0, mm + 1, 3):
            f.write(
                "        " + ", ".join(mp.nstr(x, 21) for x in v[i : i + 3]) + ",\n"
            )
        f.write("    ]),\n")
    f.write("];\n")
