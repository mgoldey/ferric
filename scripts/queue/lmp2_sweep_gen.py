#!/usr/bin/env python3
"""Helper for scripts/queue/lmp2_sweep.sh (integral-direct amplitude-threshold
LMP2 quiet-box sweep; replicates + extends wiki/amplitude-threshold-lmp2.md
§33/§34). Stdlib only. Subcommands:

  plan     write one TOML per cell + the interleaved run order (plan.tsv)
  sample   print one JSON line: load1/5, memory PSI, /proc/stat CPU jiffies
  gate-ok  exit 0 iff load1 < --load-max AND memory PSI some avg10 == 0
  predict  eps=1e-5 memory skip rule for one (op, N) from rows measured so far
  row      assemble one JSON row from a finished (or killed/skipped) run

Settings replicated from the §29/§33/§34 bench (bench_direct_alkane_series in
crates/ferric-mp2/tests/lmp2_direct.rs): 6-31G / cc-pvdz-ri, frozen_core = nc,
RHF energy_conv 1e-10, maps r_aux 10 / r_virt 12 / ao_tail 1e-3 /
schwarz_skip 1e-5 / batch_merge 4, virt_schwarz_kappa off, pair gate ON with
gate_cal 0.7 (Coulomb) / 0.02 (erfc), erfc omega = 1.0 Bohr^-1.
KNOWN differences from the bench (recorded, not hidden): the CLI's eri3 budget
comes from FERRIC_MEM_BUDGET_GB (bench pinned 2 GiB) and the CLI's direct
scratch budget is DirectConfig's default 2 GiB (bench pinned 1 GiB); the exact
erfc reference is the CLI's att-rimp2 path (attenuated_ri_mp2), not
ri_mp2(Operator::erfc) as in the bench.
"""
import argparse
import hashlib
import json
import math
import os
import re
import socket
import sys
import time

BOHR_TO_ANGSTROM = 0.529177210903
# erfc(omega r)/r with omega = 1.0 Bohr^-1, as Operator::erfc(1.0) in the
# bench. The CLI reads [mp2] omega in Angstrom^-1 and multiplies by
# BOHR_TO_ANGSTROM, so 1.0 Bohr^-1 is written as 1/0.529177... A^-1.
ERFC_OMEGA_BOHR = 1.0
ERFC_OMEGA_ANG = ERFC_OMEGA_BOHR / BOHR_TO_ANGSTROM
GATE_CAL = {"coul": 0.7, "erfc": 0.02}


def eps_tag(eps):
    return "e%d" % round(-math.log10(eps))


def n_occ_active(n_c):
    """Active occupieds of CnH2n+2 with frozen_core = n: 3n+1."""
    return 3 * n_c + 1


# --------------------------------------------------------------------- plan
def toml_text(cell, xyz):
    n, op = cell["n"], cell["op"]
    kind = "rimp2" if op == "coul" else "att-rimp2"
    lines = [
        "# generated by scripts/queue/lmp2_sweep_gen.py -- do not edit by hand",
        "[molecule]",
        'xyz = "%s"' % xyz,
        "",
        "[basis]",
        'name = "6-31g"',
        "",
        "[method]",
        'kind = "%s"' % kind,
        "",
        "[scf]",
        "energy_conv = 1e-10",
        "",
        "[mp2]",
        'auxbasis = "cc-pvdz-ri"',
        "frozen_core = %d" % n,
    ]
    if op == "erfc":
        lines += [
            'att_operator = "erfc"',
            "omega = %.12f   # Angstrom^-1 == %.1f Bohr^-1" % (ERFC_OMEGA_ANG, ERFC_OMEGA_BOHR),
        ]
    if cell["kind"] == "local":
        lines += [
            "",
            "[local]",
            'scheme = "amplitude-threshold"',
            "eps = %.0e" % cell["eps"],
            "integral_direct = true",
            "aux_radius = 10.0",
            "virt_radius = 12.0",
            "ao_tail = 1e-3",
            "schwarz_skip = 1e-5",
            "batch_merge = 4",
            "gate_cal = %s" % GATE_CAL[op],
        ]
    return "\n".join(lines) + "\n"


def cell_id(c):
    if c["kind"] == "ref":
        return "c%d_%s_exact" % (c["n"], c["op"])
    return "c%d_%s_%s" % (c["n"], c["op"], eps_tag(c["eps"]))


def build_order(cells, reps, seed):
    """Interleaved run order. Rep k is a seeded shuffle rotated by k*len/reps,
    so no cell's reps run back to back. Constraints: in rep 1 the smallest-N
    eps=1e-5 cells run FIRST (they are the memory probe for the skip rule),
    and within every rep the eps=1e-5 cells of one operator run in ascending
    N (so the prediction for N uses the largest smaller N measured)."""
    import random

    base = list(cells)
    random.Random(seed).shuffle(base)
    tight = min((c["eps"] for c in cells if c["kind"] == "local"), default=None)
    order = []
    for r in range(reps):
        k = (r * len(base)) // reps
        seq = base[k:] + base[:k]
        for op in sorted({c["op"] for c in seq}):
            pos = [i for i, c in enumerate(seq) if c["kind"] == "local" and c["eps"] == tight and c["op"] == op]
            ordered = sorted((seq[i] for i in pos), key=lambda c: c["n"])
            for i, c in zip(pos, ordered):
                seq[i] = c
        if r == 0 and tight is not None:
            n_min = min(c["n"] for c in seq if c["kind"] == "local" and c["eps"] == tight)
            probes = [c for c in seq if c["kind"] == "local" and c["eps"] == tight and c["n"] == n_min]
            seq = probes + [c for c in seq if c not in probes]
        order += [(r + 1, c) for c in seq]
    # never two reps of one cell adjacent (the rep boundary is the risk)
    for (_, a), (_, b) in zip(order, order[1:]):
        if cell_id(a) == cell_id(b):
            raise SystemExit("plan: adjacent repeat of %s; change --seed" % cell_id(a))
    return order


def cmd_plan(a):
    sizes = [int(x) for x in a.sizes.split(",")]
    epss = [float(x) for x in a.eps.split(",")]
    ops = a.ops.split(",")
    ref_sizes = [int(x) for x in a.ref_sizes.split(",")] if a.ref_sizes else []
    cells = [{"kind": "local", "n": n, "op": op, "eps": e} for n in sizes for op in ops for e in epss]
    cells += [{"kind": "ref", "n": n, "op": op, "eps": None} for n in ref_sizes for op in ops]
    tdir = os.path.join(a.out, "tomls")
    os.makedirs(tdir, exist_ok=True)
    for c in cells:
        xyz = os.path.abspath(os.path.join(a.molecules, "alkane_%d.xyz" % c["n"]))
        if not os.path.isfile(xyz) and not a.allow_missing_xyz:
            raise SystemExit("plan: missing geometry %s" % xyz)
        with open(os.path.join(tdir, cell_id(c) + ".toml"), "w") as f:
            f.write(toml_text(c, xyz))
    order = build_order(cells, a.reps, a.seed)
    with open(os.path.join(a.out, "plan.tsv"), "w") as f:
        for idx, (rep, c) in enumerate(order, 1):
            f.write(
                "%d\t%d\t%s\t%s\t%d\t%s\t%s\t%s\n"
                % (idx, rep, cell_id(c), c["kind"], c["n"], c["op"], "-" if c["eps"] is None else "%.0e" % c["eps"],
                   os.path.join(tdir, cell_id(c) + ".toml"))
            )
    print("plan: %d cells, %d runs -> %s" % (len(cells), len(order), os.path.join(a.out, "plan.tsv")))


# ------------------------------------------------------------------- sample
def read_sample():
    s = {"ts": time.time()}
    with open("/proc/loadavg") as f:
        p = f.read().split()
    s["load1"], s["load5"] = float(p[0]), float(p[1])
    try:
        with open("/proc/pressure/memory") as f:
            for line in f:
                kind, *kv = line.split()
                d = dict(x.split("=") for x in kv)
                s["psi_mem_%s_avg10" % kind] = float(d["avg10"])
                s["psi_mem_%s_avg60" % kind] = float(d["avg60"])
    except OSError:
        s["psi_mem_some_avg10"] = None
    with open("/proc/stat") as f:
        cpu = [int(x) for x in f.readline().split()[1:]]
    user, nice, system, idle, iowait, irq, softirq, steal = (cpu + [0] * 8)[:8]
    s["cpu_busy_jiffies"] = user + nice + system + irq + softirq + steal
    s["cpu_iowait_jiffies"] = iowait
    s["cpu_idle_jiffies"] = idle
    s["clk_tck"] = os.sysconf("SC_CLK_TCK")
    with open("/proc/meminfo") as f:
        for line in f:
            if line.startswith("MemAvailable:"):
                s["mem_available_kb"] = int(line.split()[1])
    return s


def cmd_sample(a):
    print(json.dumps(read_sample()))


def cmd_gate_ok(a):
    s = read_sample()
    ok = s["load1"] < a.load_max and s.get("psi_mem_some_avg10") == 0.0
    sys.exit(0 if ok else 1)


# ------------------------------------------------------------------ predict
def load_rows(path):
    rows = []
    if path and os.path.exists(path):
        with open(path) as f:
            for line in f:
                line = line.strip()
                if line:
                    rows.append(json.loads(line))
    return rows


def predict(rows, op, n, eps, skip_gb, safety):
    """Memory skip rule for an untested (op, eps, N): extrapolate the peak RSS
    of the largest SMALLER N measured at the same (op, eps).

    - A row at smaller N killed by the RSS watchdog => SKIP (it can only grow).
    - No measured smaller N => SKIP (never launch an unmeasured large cell).
    - Scaling in the active-occupied count no = 3N+1: LINEAR (pairs per
      occupied saturated) when the measured pair_fraction <= 0.5, QUADRATIC
      (pairs still growing with the chain) otherwise; times `safety`.
    Returns (decision, predicted_gb, basis_text)."""
    same = [r for r in rows if r["cell"]["kind"] == "local" and r["cell"]["op"] == op
            and r["cell"]["eps"] is not None and abs(r["cell"]["eps"] - eps) < 1e-15 and r["cell"]["n"] < n]
    killed = [r for r in same if r.get("status") == "killed_rss"]
    if killed:
        return "SKIP", float("inf"), "watchdog killed %s at N=%d" % (op, killed[0]["cell"]["n"])
    ok = [r for r in same if r.get("status") == "ok" and r.get("peak_rss_bytes")]
    if not ok:
        return "SKIP", float("nan"), "no measured smaller N at this (op, eps)"
    nm = max(r["cell"]["n"] for r in ok)
    at = [r for r in ok if r["cell"]["n"] == nm]
    rss = max(r["peak_rss_bytes"] for r in at)
    pf = max((r.get("pair_fraction") or 0.0) for r in at)
    expo = 2 if pf > 0.5 else 1
    pred = rss * (n_occ_active(n) / n_occ_active(nm)) ** expo * safety / 1e9
    basis = "N=%d peak %.2f GB, pair_fraction %.3f -> no^%d x %.2f safety" % (nm, rss / 1e9, pf, expo, safety)
    return ("RUN" if pred <= skip_gb else "SKIP"), pred, basis


def cmd_predict(a):
    d, pred, basis = predict(load_rows(a.rows), a.op, a.n, a.eps, a.skip_gb, a.safety)
    print("%s\t%.3f\t%s" % (d, pred, basis))


