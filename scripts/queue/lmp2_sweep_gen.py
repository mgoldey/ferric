FLOAT = r"([-+]?(?:\d+\.?\d*(?:[eE][-+]?\d+)?|NaN|inf))"


def parse_stdout(text):
    """Every number the CLI prints for a local/exact MP2 run. The JSON run log
    carries the certificate but NOT the stage timings, so those come from the
    printout's 't maps/eri3/metric/pairs/solve' line."""
    out = {}
    m = re.search(r"t maps/eri3/metric/pairs/solve\s+%s/%s/%s/%s/%s s" % ((FLOAT,) * 5), text)
    if m:
        out["stages_stdout"] = dict(zip(["t_maps_s", "t_eri3_s", "t_metric_s", "t_pairs_s", "t_solve_s"],
                                        map(float, m.groups())))
    m = re.search(r"strips rows %s/(\d+) cols %s/(\d+)\s+eri3 %sM evald / %sM skipped" % (FLOAT, FLOAT, FLOAT, FLOAT), text)
    if m:
        g = m.groups()
        out["strips"] = {"rows_mean": float(g[0]), "rows_max": int(g[1]), "cols_mean": float(g[2]),
                         "cols_max": int(g[3]), "eri3_mtriples_evald": float(g[4]), "eri3_mtriples_skipped": float(g[5])}
    m = re.search(r"keep %s\s+pairs %s\s+gated (\d+)\s+dom\(mean/max\) %s/(\d+)\s+cand\(mean/max\) %s/(\d+)\s+cg (\d+)"
                  % (FLOAT, FLOAT, FLOAT, FLOAT), text)
    if m:
        g = m.groups()
        out["counters"] = {"keep": float(g[0]), "pairs": float(g[1]), "gated": int(g[2]), "dom_mean": float(g[3]),
                           "dom_max": int(g[4]), "cand_mean": float(g[5]), "cand_max": int(g[6]), "cg_iterations": int(g[7])}
    m = re.search(r"omega = %s Bohr\^-1" % FLOAT, text)
    if m:
        out["omega_bohr_printed"] = float(m.group(1))
    m = re.search(r"Attenuated RI-MP2 \(erfc\).*?ω=%s" % FLOAT, text)
    if m:
        out["omega_ang_printed"] = float(m.group(1))
    m = re.search(r"locality maps\s+= (.*)", text)
    if m:
        out["locality_maps_line"] = m.group(1).strip()
    m = re.search(r"PCG gather plan\s+= (.*)", text)
    if m:
        out["pcg_gather_plan_line"] = m.group(1).strip()
    m = re.search(r"E_corr\(local MP2\)\s+= %s" % FLOAT, text) or re.search(r"MP2 corr\s+= %s" % FLOAT, text)
    if m:
        out["e_corr_stdout"] = float(m.group(1))
    return out


def parse_runlog(path):
    out = {"runlog_present": False}
    if not path or not os.path.exists(path):
        return out
    recs = []
    with open(path) as f:
        for line in f:
            try:
                recs.append(json.loads(line))
            except ValueError:
                continue
    out["runlog_present"] = True
    scf_t = [r.get("t") for r in recs if r.get("record") in ("scf_iter", "ladder_rung") and r.get("t") is not None]
    res = [r for r in recs if r.get("record") == "result"]
    end = [r for r in recs if r.get("record") == "run_end"]
    start = [r for r in recs if r.get("record") == "run_start"]
    if start:
        out["git_sha_runlog"] = start[0].get("git_sha")
        out["ferric_version_runlog"] = start[0].get("ferric_version")
        cfg = start[0].get("config") or {}
        # threads/budget/J-K route exactly as the binary resolved them
        out["run_config"] = cfg
        for k in ("rayon_num_threads", "openblas_num_threads", "memory_budget_bytes", "scf_jk"):
            if k in cfg:
                out[k] = cfg[k]
    if scf_t:
        out["t_scf_end_s"] = max(scf_t)
    if res:
        r = res[-1]
        out["t_result_s"] = r.get("t")
        out["result"] = {k: v for k, v in r.items() if k not in ("record", "seq", "t")}
        if scf_t and r.get("t") is not None:
            # Everything after the last SCF record up to the result: aux prep,
            # localization, VV-HV, assembly, solve (local) or ri_mp2 (exact).
            out["t_post_scf_s"] = r["t"] - max(scf_t)
    if end:
        e = end[-1]
        out["run_end"] = {k: e.get(k) for k in ("wall_s", "cpu_s", "peak_rss_bytes", "converged", "exit")}
        ex = e.get("extra") or {}
        out["run_end_extra"] = ex
    return out


def parse_time_v(path):
    out = {}
    if not path or not os.path.exists(path):
        return out
    keys = {"User time (seconds)": "user_s", "System time (seconds)": "sys_s",
            "Maximum resident set size (kbytes)": "max_rss_kb", "Exit status": "time_exit_status",
            "Percent of CPU this job got": "pct_cpu", "Major (requiring I/O) page faults": "major_faults",
            "Involuntary context switches": "invol_ctx_switches"}
    with open(path) as f:
        for line in f:
            line = line.strip()
            for k, name in keys.items():
                if line.startswith(k + ":"):
                    v = line.split(":", 1)[1].strip().rstrip("%")
                    try:
                        out[name] = float(v) if "." in v else int(v)
                    except ValueError:
                        out[name] = v
            if line.startswith("Elapsed (wall clock) time"):
                v = line.rsplit(" ", 1)[-1]
                parts = [float(x) for x in v.split(":")]
                sec = 0.0
                for p in parts:
                    sec = sec * 60 + p
                out["elapsed_s"] = sec
    return out


def contention(before, after, wall, own_cpu_s, threads, load_excess_max, foreign_cores_max):
    """Judge FOREIGN activity only (memory post-sample-load-gate-biases-
    timings-fast): raw load1 after a 6-thread run includes the run itself.
    Flags never discard a row."""
    c = {}
    if not (before and after and wall and wall > 0):
        return c, []
    decay = math.exp(-wall / 60.0)
    own_par = (own_cpu_s / wall) if own_cpu_s is not None else float(threads)
    expected = before["load1"] * decay + own_par * (1.0 - decay)
    c["load1_before"], c["load1_after"] = before["load1"], after["load1"]
    c["own_parallelism"] = own_par
    c["load1_after_expected_own"] = expected
    c["load1_after_excess"] = after["load1"] - expected
    tck = after.get("clk_tck") or 100
    busy_s = (after["cpu_busy_jiffies"] - before["cpu_busy_jiffies"]) / tck
    c["box_busy_cpu_s"] = busy_s
    if own_cpu_s is not None:
        c["foreign_cpu_s"] = busy_s - own_cpu_s
        c["foreign_cores_avg"] = c["foreign_cpu_s"] / wall
    c["iowait_s"] = (after["cpu_iowait_jiffies"] - before["cpu_iowait_jiffies"]) / tck
    c["psi_some_avg10_before"] = before.get("psi_mem_some_avg10")
    c["psi_some_avg10_after"] = after.get("psi_mem_some_avg10")
    flags = []
    if c["load1_after_excess"] > load_excess_max:
        flags.append("load_excess")
    if c.get("foreign_cores_avg") is not None and c["foreign_cores_avg"] > foreign_cores_max:
        flags.append("foreign_cpu")
    if (c["psi_some_avg10_after"] or 0.0) > 0.0:
        flags.append("mem_pressure_after")
    if (c["psi_some_avg10_before"] or 0.0) > 0.0:
        flags.append("mem_pressure_before")
    return c, flags


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def parse_version(path):
    d = {}
    if path and os.path.exists(path):
        with open(path) as f:
            for i, line in enumerate(f):
                line = line.rstrip("\n")
                if i == 0:
                    d["version"] = line
                elif ":" in line:
                    k, v = line.split(":", 1)
                    d[k.strip()] = v.strip()
    return d


def cmd_row(a):
    cell = {"kind": a.kind, "n": a.n, "op": a.op, "eps": None if a.eps in ("-", "") else float(a.eps)}
    row = {"schema": "lmp2_sweep/1", "run_idx": a.run_idx, "rep": a.rep, "cell_id": a.cell_id, "cell": cell,
           "status": a.status, "exit_code": a.exit_code, "wall_s": a.wall, "started_at": a.started_at}
    if a.skip_reason:
        row["skip_reason"] = a.skip_reason
    if a.predicted_gb is not None:
        row["predicted_peak_gb"] = a.predicted_gb
    row["gate"] = {"waited_s": a.gate_waited, "timed_out": bool(a.gate_timeout)}
    before = json.loads(a.before) if a.before else None
    after = json.loads(a.after) if a.after else None
    row["sample_before"], row["sample_after"] = before, after
    if a.status != "skipped_mem":
        tv = parse_time_v(a.timefile)
        row["time_v"] = tv
        rl = parse_runlog(a.jsonl)
        row["runlog"] = {k: v for k, v in rl.items() if k not in ("result",)}
        res = rl.get("result") or {}
        comps = res.get("components", res)
        row["result"] = res
        row["e_corr"] = comps.get("e_corr")
        row["e_corr_canonical_ri"] = comps.get("e_corr_canonical_ri")
        row["e_scf_reference"] = comps.get("e_scf_reference")
        row["scf_converged"] = comps.get("scf_converged")
        local = comps.get("local")
        row["certificate"] = local
        if isinstance(local, dict):
            row["keep_fraction"] = local.get("keep_fraction")
            row["pair_fraction"] = local.get("pair_fraction")
            row["build_commit"] = local.get("build_commit")
            row["build_dirty"] = local.get("build_dirty")
        # Future-proof: if a later CLI emits stage timings in JSON, keep them.
        st = None
        for src in (comps, local if isinstance(local, dict) else {}):
            for k in ("timings", "stage_timings", "direct_stats"):
                if isinstance(src.get(k), dict):
                    st = dict(st or {}, **{k: src[k]})
        row["stage_timings_json"] = st
        so = ""
        if a.stdout and os.path.exists(a.stdout):
            with open(a.stdout, errors="replace") as f:
                so = f.read()
        row.update(parse_stdout(so))
        if "stages_stdout" in row:
            row["method_stage_sum_s"] = sum(row["stages_stdout"].values())
        row["t_post_scf_s"] = rl.get("t_post_scf_s")
        re_ = rl.get("run_end") or {}
        row["peak_rss_bytes"] = re_.get("peak_rss_bytes") or (tv.get("max_rss_kb", 0) * 1024 or None)
        if a.watchdog_max_rss_kb:
            row["watchdog_max_rss_kb"] = a.watchdog_max_rss_kb
        own = None
        if "user_s" in tv and "sys_s" in tv:
            own = tv["user_s"] + tv["sys_s"]
        elif re_.get("cpu_s") is not None:
            own = re_["cpu_s"]
        c, flags = contention(before, after, a.wall, own, a.threads, a.load_excess_max, a.foreign_cores_max)
        row["contention"] = c
        if a.gate_timeout:
            flags.append("gate_timeout")
        row["flags"] = flags
        if a.stderr and os.path.exists(a.stderr):
            with open(a.stderr, errors="replace") as f:
                err = f.read()
            row["stderr_tail"] = err[-2000:]
    row["env"] = {
        "OPENBLAS_NUM_THREADS": os.environ.get("OPENBLAS_NUM_THREADS"),
        "RAYON_NUM_THREADS": os.environ.get("RAYON_NUM_THREADS"),
        "FERRIC_MEM_BUDGET_GB": os.environ.get("FERRIC_MEM_BUDGET_GB"),
        "hostname": socket.gethostname(),
        "kernel": os.uname().release,
        "binary": a.binary,
        "binary_sha256": sha256(a.binary) if a.binary and os.path.exists(a.binary) else None,
        "rss_kill_gb": a.rss_kill_gb,
        "cgroup_cap": None,
    }
    row["version"] = parse_version(a.version_file)
    print(json.dumps(row, sort_keys=True))


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sp = p.add_subparsers(dest="cmd", required=True)
    q = sp.add_parser("plan")
    q.add_argument("--out", required=True)
    q.add_argument("--molecules", required=True, help="dir holding alkane_<N>.xyz")
    q.add_argument("--sizes", default="20,32,48")
    q.add_argument("--eps", default="1e-3,1e-4,1e-5")
