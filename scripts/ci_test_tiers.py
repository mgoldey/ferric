#!/usr/bin/env python3
"""List the TIERED tests: the ones a CI shard defers unless their crate changed.

A tiered test carries exactly one of these attributes:

    #[ignore = "tier medium (10-60s): CI runs it when an affected crate changes (scripts/ci_test_tiers.py)"]
    #[ignore = "tier slow (>=60s): CI runs it when an affected crate changes (scripts/ci_test_tiers.py)"]
    #[ignore = "tier exhaustive: CI runs it when an affected crate changes (scripts/ci_test_tiers.py)"]

The tier is the test's wall time in a release-build nextest run on a 6-core
box (2026-11): medium and slow by duration, exhaustive for threshold/system
sweeps worth running only when their code changes. To tier a new test, add
the attribute; to un-tier one, delete it. Nothing else needs editing.

Running them locally: `cargo nextest run --run-ignored only -E
"$(scripts/ci_test_tiers.py filter)"`, narrowed with `& rdeps(<crate>)`.

Any OTHER #[ignore] reason is a precondition ("run serially on a quiet box",
"validation: ...", a measurement) and must never be swept into a CI run, which
is why selection is by these exact strings and by name, not by `--run-ignored`
alone.

    scripts/ci_test_tiers.py filter
        A nextest filterset matching exactly the tiered tests. Use it with
        `--run-ignored only`.
    scripts/ci_test_tiers.py check <list.json>
        <list.json> is `cargo nextest list --workspace --all-targets
        --run-ignored only -E "$(scripts/ci_test_tiers.py filter)"
        --message-format json`. Fails unless the filter matches every tiered
        test found in the source and nothing else.

A test generated by a macro_rules! whose body carries the attribute is
expanded to the macro's invocations in the same file. Anything the scanner
cannot resolve is an error, not a skip.
"""

import json
import os
import re
import subprocess
import sys
from collections import defaultdict

TIER = re.compile(
    r'^\s*#\[ignore = "tier (medium \(10-60s\)|slow \(>=60s\)|exhaustive): '
    r'CI runs it when an affected crate changes \(scripts/ci_test_tiers\.py\)"\]\s*$'
)
FN = re.compile(
    r"^\s*(?:pub(?:\([^)]*\))?\s+)?(?:async\s+)?fn\s+(\$?[A-Za-z_][A-Za-z0-9_]*)"
)


def die(msg):
    print(f"ci_test_tiers: {msg}", file=sys.stderr)
    sys.exit(1)


def targets(root):
    """{abs src_path: binary_id}, {package src dir: (lib binary_id, crate root)}."""
    meta = json.loads(
        subprocess.run(
            ["cargo", "metadata", "--no-deps", "--format-version", "1", "--offline"],
            capture_output=True,
            text=True,
            check=True,
            cwd=root,
        ).stdout
    )
    roots, src_dirs = {}, {}
    for pkg in meta["packages"]:
        name = pkg["name"]
        for t in pkg["targets"]:
            path = os.path.realpath(t["src_path"])
            kinds = set(t["kind"])
            if "test" in kinds:
                roots[path] = f"{name}::{t['name']}"
            elif kinds & {"lib", "rlib", "cdylib", "proc-macro", "staticlib", "dylib"}:
                roots[path] = name
                src_dirs[os.path.dirname(path)] = (name, path)
            elif "bin" in kinds:
                roots[path] = f"{name}::bin/{t['name']}"
    return roots, src_dirs


def owner(path, roots, src_dirs):
    """(binary_id, module prefix regex) for a .rs file holding a tiered test."""
    if path in roots:
        return roots[path], ""  # a crate root: tests sit at the top level
    for src_dir, (bid, _) in sorted(src_dirs.items(), key=lambda kv: -len(kv[0])):
        if path.startswith(src_dir + os.sep):
            rel = os.path.relpath(path, src_dir)[: -len(".rs")].split(os.sep)
            if rel[-1] == "mod":
                rel = rel[:-1]
            return bid, "::".join(rel) + "::"
    die(f"{path}: not a target root nor under a library's src/ (shared test module?)")


def scan(root):
    """{binary_id: set of (module prefix, test fn name)}, and the count found."""
    roots, src_dirs = targets(root)
    canaries = set(
        subprocess.run(
            [os.path.join(root, "scripts/ci-malloc-perturb-canaries.sh"), "ids"],
            capture_output=True,
            text=True,
            check=True,
        ).stdout.split()
    )
    if not canaries:
        die("scripts/ci-malloc-perturb-canaries.sh ids printed nothing")
    found = defaultdict(set)
    files = subprocess.run(
        ["git", "ls-files", "-z", "--", "*.rs"],
        capture_output=True,
        text=True,
        check=True,
        cwd=root,
    ).stdout.split("\0")
    for rel in filter(None, files):
        path = os.path.realpath(os.path.join(root, rel))
        lines = open(path, encoding="utf-8").read().split("\n")
        hits = [i for i, line in enumerate(lines) if TIER.match(line)]
        if not hits:
            continue
        bid, prefix = owner(path, roots, src_dirs)
        if bid.split("::")[-1].startswith("validation_"):
            # The validation tier runs weekly against committed references;
            # a tier tag there would put it on every PR (ci_validation_tier_guard).
            die(
                f"{rel}: a tier tag in validation binary {bid}; validation tests keep "
                '#[ignore = "validation: <row>"]'
            )
        if bid.split("::")[-1].startswith("mpi_"):
            # ci.yml's mpi job runs these binaries itself under mpirun and
            # asserts an exact passing-test count per rank; a tier tag makes
            # that count 0 (PR #626, mpi_df_b3lyp_water_and_benzene_banded).
            die(f"{rel}: a tier tag in MPI binary {bid}; the mpi job runs it by name")
        if bid in canaries:
            # malloc-perturb runs these binaries' NON-ignored tests under
            # MALLOC_PERTURB_; a tier tag silently drops a test from that set.
            die(f"{rel}: a tier tag in malloc-perturb canary binary {bid}")
        for i in hits:
            name = None
            for line in lines[i + 1 : i + 40]:
                m = FN.match(line)
                if m:
                    name = m.group(1)
                    break
            if name is None:
                die(f"{rel}:{i + 1}: no fn follows the tier attribute")
            names = [name]
            if name.startswith("$"):
                macro = None
                for line in reversed(lines[:i]):
                    m = re.match(r"^\s*macro_rules!\s+([A-Za-z_][A-Za-z0-9_]*)", line)
                    if m:
                        macro = m.group(1)
                        break
                if macro is None:
                    die(f"{rel}:{i + 1}: {name} outside a macro_rules!")
                names = re.findall(
                    rf"^\s*{macro}!\s*[\(\[{{]\s*([A-Za-z_][A-Za-z0-9_]*)",
                    "\n".join(lines),
                    re.M,
                )
                if not names:
                    die(f"{rel}:{i + 1}: macro {macro}! is never invoked")
            for n in names:
                if (prefix, n) in found[bid]:
                    die(f"{rel}: test {n} tiered twice in {bid}")
                found[bid].add((prefix, n))
    return found


def filterset(found):
    terms = []
    for bid in sorted(found):
        by_prefix = defaultdict(list)
        for prefix, name in found[bid]:
            by_prefix[prefix].append(name)
        alts = []
        for prefix in sorted(by_prefix):
            names = "|".join(sorted(by_prefix[prefix]))
            # A crate-root file may still wrap tests in `mod tests { }`.
            alts.append(f"^{re.escape(prefix)}(.*::)?({names})$")
        terms.append(f"(binary_id(={bid}) & test(/{'|'.join(alts)}/))")
    return " | ".join(terms) if terms else "none()"


def check(found, list_json):
    data = json.load(open(list_json))
    got = defaultdict(set)
    for bid, suite in data["rust-suites"].items():
        for name, case in suite["testcases"].items():
            if case["filter-match"]["status"] == "matches":
                got[bid].add(name)
    problems = []
    for bid, tests in found.items():
        for prefix, name in tests:
            hit = [
                t
                for t in got.get(bid, ())
                if t.startswith(prefix) and t.split("::")[-1] == name
            ]
            if len(hit) != 1:
                problems.append(
                    f"{bid}: {prefix}{name} matched {len(hit)} listed test(s)"
                )
    n_src = sum(len(v) for v in found.values())
    n_got = sum(len(v) for v in got.values())
    if n_got != n_src:
        problems.append(
            f"filter matched {n_got} ignored tests, source has {n_src} tiered"
        )
    if problems:
        print("\n".join(problems[:40]), file=sys.stderr)
        die(f"{len(problems)} problem(s)")
    print(
        f"ci_test_tiers: {n_src} tiered tests in {len(found)} binaries, filter matches exactly"
    )


def main():
    root = subprocess.run(
        ["git", "rev-parse", "--show-toplevel"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()
    found = scan(root)
    if sys.argv[1:] == ["filter"]:
        print(filterset(found))
    elif len(sys.argv) == 3 and sys.argv[1] == "check":
        check(found, sys.argv[2])
    else:
        die("usage: ci_test_tiers.py filter | check <list.json>")


if __name__ == "__main__":
    main()
