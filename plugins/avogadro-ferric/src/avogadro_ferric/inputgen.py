"""Input generator: a ferric CLI TOML input plus its XYZ geometry.

The CLI's ``[molecule] xyz`` is a path (crates/ferric-cli/src/config.rs,
MoleculeCfg) resolved against the working directory, so the generator writes
two files, ``<base>.toml`` and ``<base>.xyz``, and the run command is
``ferric <base>.toml`` from the directory holding both. Every section the
generator writes is ``deny_unknown_fields`` in ferric's schema; the tests run
the real CLI on generated inputs.
"""

from __future__ import annotations

import json
import re

import numpy as np

from .engine import ELEMENT_SYMBOLS

TASKS = {
    "Single Point": "energy",
    "Equilibrium Geometry": "optimize",
    "Frequencies": "frequencies",
}


def _toml_string(s: str) -> str:
    return json.dumps(str(s))  # a JSON string literal is a valid TOML basic string


def _safe_base(base: str) -> str:
    base = re.sub(r"[^A-Za-z0-9_.-]+", "_", str(base).strip()) or "job"
    return base


def xyz_text(cjson: dict, title: str) -> str:
    numbers = cjson["atoms"]["elements"]["number"]
    coords = np.asarray(cjson["atoms"]["coords"]["3d"], dtype=float).reshape(-1, 3)
    lines = [str(len(numbers)), title.replace("\n", " ")]
    for z, (x, y, zc) in zip(numbers, coords):
        lines.append(f"{ELEMENT_SYMBOLS[int(z)]:<2} {x:16.10f} {y:16.10f} {zc:16.10f}")
    return "\n".join(lines) + "\n"


def toml_text(opts: dict, base: str) -> str:
    calc = opts.get("Calculation Type", "Single Point")
    if calc not in TASKS:
        raise ValueError(f"unknown calculation type {calc!r}")
    task = TASKS[calc]
    theory = str(opts.get("Theory", "HF"))
    basis = str(opts.get("Basis", "sto-3g"))
    charge = int(opts.get("Charge", 0))
    mult = int(opts.get("Multiplicity", 1))
    cores = int(opts.get("Processor Cores", 0) or 0)
    memory = float(opts.get("Memory", 0.0) or 0.0)
    dispersion = str(opts.get("Dispersion", "none"))
    is_hf = theory.upper() == "HF"
    if is_hf:
        kind = "rhf" if mult == 1 else "uhf"
    else:
        kind = "ksdft"

    run = f"ferric {base}.toml"
    if cores > 0:
        run = f"RAYON_NUM_THREADS={cores} {run}"
    out = [
        f"# {opts.get('Title', 'ferric calculation')}".rstrip(),
        "# Generated by the avogadro-ferric input generator.",
        f"# Run from the directory holding {base}.toml and {base}.xyz:",
        f"#   {run}",
        "",
        "[molecule]",
        f"xyz = {_toml_string(base + '.xyz')}",
        f"charge = {charge}",
        f"multiplicity = {mult}",
        "",
        "[basis]",
        f"name = {_toml_string(basis)}",
        "",
        "[method]",
        f"kind = {_toml_string(kind)}",
        f"task = {_toml_string(task)}",
    ]
    if not is_hf:
        out += ["", "[dft]", f"functional = {_toml_string(theory)}"]
        if dispersion != "none":
            out.append(f"dispersion = {_toml_string(dispersion)}")
    if memory > 0:
        out += ["", "[memory]", f"budget_gb = {memory:g}"]
    return "\n".join(out) + "\n"


def generate(avo_input: dict) -> dict:
    opts = avo_input.get("options", {}) or {}
    cjson = avo_input.get("cjson")
    if isinstance(cjson, str):
        cjson = json.loads(cjson)
    try:
        base = _safe_base(opts.get("Filename Base", "job"))
        toml = toml_text(opts, base)
        xyz = xyz_text(cjson, str(opts.get("Title", "ferric calculation")))
    except Exception as exc:  # shown to the user as a warning in the dialog
        return {"warnings": [str(exc)], "files": []}
    return {
        "files": [
            {
                "filename": f"{base}.toml",
                "contents": toml,
                "highlightStyles": ["ferric"],
            },
            {"filename": f"{base}.xyz", "contents": xyz},
        ],
        "mainFile": f"{base}.toml",
    }
