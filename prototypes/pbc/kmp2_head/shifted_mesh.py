def gen(m, s):
    import pbc_kcorr as KC
    import pbc_kpts as PK
    import run_kcorr_head_anomaly as HA
    from pbc_gamma import Cell
    from run_kpts_anchor import H2_ATOMS

    out = _npz(m, s, regen=(s == 0))
    assert not os.path.exists(out), f"refusing to overwrite {out}"
    cell = Cell(np.eye(3) * A_CELL, H2_ATOMS, "sto-3g")
    gcut = PK.aft_gcut(cell, 1e-10)
    n = (m, m, m)
    shift = None if s == 0 else (s, s, s)
    t0 = time.time()
    kb = PK.build_k(cell, n, exxdiv="ewald", gcut=gcut, verbose=False, shift=shift)
    e_hf, eps, it, C, occ = PK.krhf(kb, 2, conv=1e-12, kshift=0.0, return_mo=True)
    assert all(int(o.sum()) == 1 and o[0] for o in occ)
    vm = kb["madelung"]
    t1 = time.time()
    gap = min(e[1] for e in eps) - max(e[0] for e in eps)
    print(
        f"scf {t1 - t0:.0f}s HF(none) {e_hf:.12f} it {it} v_M {vm:.10f} gap {gap:.4f}",
        flush=True,
    )
    st = KC.aft_ov(cell, n, C, 1, gcut=gcut, shift=shift)
    st["Co"], st["Cv"] = KC._mo_stacks(C, 1)
    t2 = time.time()
    print(f"aft_ov {t2 - t1:.0f}s", flush=True)
    eo, ev = KC.k_denominators(eps, 1, vm, "shifted")
    P0, A, B = HA.pair_derivs(cell, n, shift=shift)
    Nk = st["Nk"]
    a4 = max(abs(P0[k] - kb["S"][k]).max() for k in range(Nk))
    e_sh = HA.energies(st, eo, ev)
    a2 = abs(e_sh[0] - KC.kmp2(st, eo, ev)[0])
    cub = A * np.sqrt(4 * np.pi / (3 * cell.vol))
    rows = {"sh": e_sh}
    for lam in (1.0, 0.5, 2.0, 1e-3):
        rows[f"cub{lam:g}"] = HA.energies(HA.with_head(st, cub, lam), eo, ev)
    deo, dev = HA.fock_head_shifts(cell, st, P0, A, B, C, 1)
    eoF = [x - y for x, y in zip(eo, deo)]
    evF = [x - y for x, y in zip(ev, dev)]
    rows["fock"] = HA.energies(st, eoF, evF)
    rows["fock+cub"] = HA.energies(HA.with_head(st, cub), eoF, evF)
    print(f"anchors: A4 max|P0-S| {a4:.1e}; A2 {a2:.1e}")
    for key, val in rows.items():
        print(f"   {key:10s} MP2 {val[0]:.13e}  dRPA {val[1]:.13e}", flush=True)
    tt = time.time() - t0
    np.savez(
        out,
        rows=np.array([list(v) for v in rows.values()]),
        keys=np.array(list(rows.keys())),
        eps=np.array(eps),
        vm=vm,
        deo=np.array(deo),
        dev=np.array(dev),
        e_hf=e_hf,
        V=st["V"],
        Kq=st["Kq"],
        C=np.array(C),
        A=A,
        B=B,
        P0=P0,
        kpts=kb["kpts"],
        shift=np.array(shift if shift else (0.0, 0.0, 0.0)),
        anchors=np.array([a4, a2]),
        timings=np.array([t1 - t0, t2 - t1, tt]),
    )
    print(f"saved {out} ({tt:.0f}s)", flush=True)


def _rows_path(path):
    z = np.load(path)
    return dict(zip(list(z["keys"]), z["rows"])), z


def _rows(n, s):
    return _rows_path(_npz(n, s))


def analyze():
    print("== raw (MP2 per cell, Hartree)")
    print(
        "  n  shift  S                      E1 (cub1)              Hc n^3        F n^3        gap     HF(none)"
    )
    R = {}
    for n in (3, 4, 5, 6):
        for s in (0, 0.5):
            if not os.path.exists(_npz(n, s)):
                continue
            r, z = _rows(n, s)
            R[(n, s)] = r
            gap = min(e[1] for e in z["eps"]) - max(e[0] for e in z["eps"])
            ehf = float(z["e_hf"]) if "e_hf" in z.files else float("nan")
            print(
                f"  {n}  {s:<5g}  {r['sh'][0]:.13e}  {r['cub1'][0]:.13e}  {(r['cub1'][0] - r['sh'][0]) * n**3:+.5e}  "
                f"{(r['fock'][0] - r['sh'][0]) * n**3:+.5e}  {gap:.4f}  {ehf:.12f}"
            )
    for n in (3, 4):
        if os.path.exists(_npz(n, 0, regen=True)):
            rr, _ = _rows_path(_npz(n, 0, regen=True))
            for k in ("sh", "cub1"):
                d = abs(rr[k][0] - R[(n, 0)][k][0])
                print(
                    f"  Z4 n={n} s=0 regenerated by this code vs stored npz, row {k}: |diff| {d:.1e} (gate 1e-12)"
                )
    print("== shift response Delta(n) = X(shifted) - X(Gamma-centred), same n")
    D = {}
    for n in (3, 4):
        if (n, 0.5) in R and (n, 0) in R:
            a, b = R[(n, 0.5)], R[(n, 0)]
            D[n] = a["cub1"][0] - b["cub1"][0]
            print(
                f"  n={n}: dE1 {D[n]:+.4e}  dS {a['sh'][0] - b['sh'][0]:+.4e}  dHc {a['cub1'][0] - a['sh'][0] - b['cub1'][0] + b['sh'][0]:+.3e}  "
                f"dF {a['fock'][0] - a['sh'][0] - b['fock'][0] + b['sh'][0]:+.3e}  "
                f"(dRPA dE1 {a['cub1'][1] - b['cub1'][1]:+.3e})"
            )
            print(f"         twist average E1 {(a['cub1'][0] + b['cub1'][0]) / 2:.13e}")
    if 3 in D and 4 in D:
        tav = {n: (R[(n, 0.5)]["cub1"][0] + R[(n, 0)]["cub1"][0]) / 2 for n in (3, 4)}
        print(
            f"  twist-average step (3) - (4): {tav[3] - tav[4]:+.3e}  (Gamma-centred step {E1_GAMMA[3] - E1_GAMMA[4]:+.3e})"
        )
        print("== decision (pre-registered)")
        if 0.7e-7 <= D[4] <= 2.5e-7 and -2.5e-7 <= D[3] <= -0.7e-7:
            v = "SUPPORTED (H-k): the parity is k-sampling; a half shift flips it"
        elif abs(D[4]) <= 4e-8 and abs(D[3]) <= 4e-8:
            v = "REFUTED (H-q): the shift does not move E1; the parity is not in the k set"
        else:
            v = "UNDETERMINED"
        print(f"  Delta(3) {D[3]:+.3e}  Delta(4) {D[4]:+.3e}  -> {v}")


