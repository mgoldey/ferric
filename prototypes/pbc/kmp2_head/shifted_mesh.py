def _small(n, shift, mutant=None):
    """H2/STO-3G a = 4 (the oracle cell): HF, S, E1 and the raw objects."""
    import pbc_kcorr as KC
    import pbc_kpts as PK
    import run_kcorr_head_anomaly as HA
    from pbc_gamma import Cell
    from run_kpts_anchor import H2_A, H2_ATOMS

    PK._MUTANT = mutant
    try:
        cell = Cell(H2_A, H2_ATOMS, "sto-3g")
        kw = {} if shift is None else {"shift": shift}
        kb = PK.build_k(cell, n, exxdiv="ewald", verbose=False, **kw)
        e, eps, it, C, occ = PK.krhf(kb, 2, conv=1e-12, kshift=0.0, return_mo=True)
        st = KC.aft_ov(cell, n, C, 1, **kw)
        st["Co"], st["Cv"] = KC._mo_stacks(C, 1)
        eo, ev = KC.k_denominators(eps, 1, kb["madelung"], "shifted")
        S = KC.kmp2(st, eo, ev)[0]
        P0, A, B = HA.pair_derivs(cell, n, **kw)
        cub = A * np.sqrt(4 * np.pi / (3 * cell.vol))
        E1 = KC.kmp2(HA.with_head(st, cub), eo, ev)[0]
        z1 = max(abs(P0[k] - kb["S"][k]).max() for k in range(kb["Nk"]))
        return dict(cell=cell, kb=kb, e_hf=e, eps=eps, C=C, occ=occ, S=S, E1=E1, z1=z1)
    finally:
        PK._MUTANT = None


