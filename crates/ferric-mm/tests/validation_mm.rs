// The check
// ---------------------------------------------------------------------------

#[derive(Default)]
struct Worst {
    e: f64,
    g: f64,
    decomp: f64,
    ke_offset: f64,
    min_control_gap: f64,
}

fn check_structure(sys: &str, r: &Value, top: &MmTopology) {
    let n = r["n_atoms"].as_u64().unwrap() as usize;
    assert_eq!(top.n_atoms(), n, "{sys}: atom count");

    // OpenMM's 1-4 scales (measured from its exceptions) must be the ones
    // ferric applies globally.
    let s_lj = num(r, "/exception_scales/scale_lj_14");
    let s_c = num(r, "/exception_scales/scale_coul_14");
    assert!(
        (s_lj - DEFAULT_SCALE_LJ_14).abs() < TOL_SCALE
            && (top.scale_lj_14 - s_lj).abs() < TOL_SCALE,
        "{sys}: OpenMM 1-4 LJ scale {s_lj} vs ferric {}",
        top.scale_lj_14
    );
    assert!(
        (s_c - DEFAULT_SCALE_COUL_14).abs() < TOL_SCALE
            && (top.scale_coul_14 - s_c).abs() < TOL_SCALE,
        "{sys}: OpenMM 1-4 Coulomb scale {s_c} vs ferric {}",
        top.scale_coul_14
    );

    // ferric's BFS-derived pair sets vs the force field's exceptions.
    // "ambiguous" exceptions are zero whether excluded or scaled, so either
    // classification is acceptable for them.
    let excl = pair_set(r, "/exceptions/excluded");
    let p14 = pair_set(r, "/exceptions/scaled14");
    let amb = pair_set(r, "/exceptions/ambiguous");
    let f_excl: HashSet<_> = top.exclusions().iter().copied().collect();
    let f_14: HashSet<_> = top.pairs14().iter().copied().collect();
    let miss_excl: Vec<_> = excl.difference(&f_excl).collect();
    let miss_14: Vec<_> = p14.difference(&f_14).collect();
    let extra_excl: Vec<_> = f_excl
        .difference(&excl)
        .filter(|p| !amb.contains(p))
        .collect();
    let extra_14: Vec<_> = f_14.difference(&p14).filter(|p| !amb.contains(p)).collect();
    assert!(
        miss_excl.is_empty() && miss_14.is_empty() && extra_excl.is_empty() && extra_14.is_empty(),
        "{sys}: pair sets differ from OpenMM's exceptions: excluded by OpenMM only {miss_excl:?}, \
         1-4 in OpenMM only {miss_14:?}, excluded by ferric only {extra_excl:?}, \
         1-4 in ferric only {extra_14:?}"
    );
    assert!(
        !excl.is_empty() && !p14.is_empty(),
        "{sys}: an empty pair set would make the comparison vacuous"
    );
}

/// Relative error of `term` for a CONTROL topology, judged the same way as
/// the real comparison.
fn control_rel(top: &MmTopology, x: &Array2<f64>, term: &str, e_ref: f64, ke: f64) -> f64 {
    rel_e(ferric_term_energy(top, x, term, ke), e_ref)
}

fn check_system(sys: &str) {
    let r = reference(sys);
    let top = build_topology(&r);
    check_structure(sys, &r, &top);
    let ke = num(&r, "/provenance/coulomb_constant/openmm_in_hartree_bohr");
    assert!(
        (ke - 1.0).abs() < 1e-9,
        "{sys}: OpenMM Coulomb constant in ferric units is {ke}; a unit slip, not a CODATA offset"
    );
    let phases_even = r["all_torsion_phases_0_or_180"].as_bool().unwrap();

    let parts: Vec<(&str, MmTopology)> = TERMS.iter().map(|&t| (t, only(&top, t))).collect();
    let mut w = Worst {
        min_control_gap: f64::INFINITY,
        ..Default::default()
    };

    for geom in arr(&r, "/geometries") {
        let label = geom["label"].as_str().unwrap();
        let tag = format!("{sys}/{label}");
        let x = coords_bohr(geom);

        let (e_full, g_full) = gradient(&top, &x).unwrap();
        assert_eq!(
            e_full,
            energy(&top, &x).unwrap(),
            "{tag}: energy()/gradient() disagree"
        );

        // --- per term -------------------------------------------------------
        let mut g_sum = Array2::<f64>::zeros(g_full.raw_dim());
        let mut g_total_scaled = Array2::<f64>::zeros(g_full.raw_dim());
        let mut e_total_scaled = 0.0;
        let mut scale_total = 0.0;
        for (term, t) in &parts {
            let (e_t, g_t) = gradient(t, &x).unwrap();
            let e_t = term_energy(&e_t, term);
            assert_eq!(
                e_t,
                term_energy(&e_full, term),
                "{tag}: {term} energy from the term-only topology != full topology"
            );
            g_sum += &g_t;
            let k = if *term == "coulomb" { ke } else { 1.0 };
            let e_ref = num(geom, &format!("/energy_hartree/{term}"));
            let g_ref = rows(&geom["gradient_hartree_bohr"][*term]);

            if *term == "coulomb" {
                // The raw disagreement IS the Coulomb-constant offset.
                let raw = (e_ref - e_t) / e_ref;
                let off = (raw - (1.0 - 1.0 / ke)).abs();
                w.ke_offset = w.ke_offset.max(off);
                assert!(
                    off < TOL_E_REL,
                    "{tag}: raw Coulomb rel. difference {raw:.3e} is not the constant offset \
                     {:.3e} (residual {off:.3e})",
                    1.0 - 1.0 / ke
                );
            }

            let de = rel_e(k * e_t, e_ref);
            let dg = rel_g(&(&g_t * k), &g_ref);
            eprintln!("{tag:34} {term:8} E_ref {e_ref:+.10e}  dE_rel {de:.2e}  dG_rel {dg:.2e}");
            w.e = w.e.max(de);
            w.g = w.g.max(dg);
            assert!(de < TOL_E_REL, "{tag}: {term} energy rel. error {de:.3e}");
            assert!(dg < TOL_G_REL, "{tag}: {term} gradient rel. error {dg:.3e}");

            e_total_scaled += k * e_t;
            g_total_scaled += &(&g_t * k);
            scale_total += e_ref.abs();
        }

        let decomp = rel_g(&g_sum, &g_full);
        w.decomp = w.decomp.max(decomp);
        assert!(
            decomp < TOL_DECOMP_REL,
            "{tag}: per-term gradients do not sum to gradient(): {decomp:.3e}"
        );

        // --- total ------------------------------------------------------------
        let e_ref_tot = num(geom, "/energy_hartree/total");
        let de_tot = (e_total_scaled - e_ref_tot).abs() / scale_total;
        let dg_tot = rel_g(
            &g_total_scaled,
            &rows(&geom["gradient_hartree_bohr"]["total"]),
        );
        eprintln!(
            "{tag:34} total    E_ref {e_ref_tot:+.10e}  dE_rel {de_tot:.2e}  dG_rel {dg_tot:.2e}"
        );
        w.e = w.e.max(de_tot);
        w.g = w.g.max(dg_tot);
        assert!(
            de_tot < TOL_E_REL,
            "{tag}: total energy rel. error {de_tot:.3e}"
        );
        assert!(
            dg_tot < TOL_G_REL,
            "{tag}: total gradient rel. error {dg_tot:.3e}"
        );

        // --- negative controls ---------------------------------------------
        let e_ref = |t: &str| num(geom, &format!("/energy_hartree/{t}"));
        let bar = MISS_FACTOR * TOL_E_REL;
        let mut expect_miss = |what: &str, t: &MmTopology, term: &str| {
            let gap = control_rel(t, &x, term, e_ref(term), ke);
            eprintln!("{tag:34} control {what}: {term} rel. gap {gap:.2e}");
            w.min_control_gap = w.min_control_gap.min(gap);
            assert!(
                gap > bar,
                "{tag}: control '{what}' reproduced the reference {term} (gap {gap:.3e} <= {bar:.1e}); \
                 the comparison cannot see that defect"
            );
        };

        let unscaled = top.clone().with_scales(1.0, 1.0);
        expect_miss("1-4 scales = 1", &unscaled, "coulomb");
        expect_miss("1-4 scales = 1", &unscaled, "lj");

        let swapped = top
            .clone()
            .with_scales(DEFAULT_SCALE_COUL_14, DEFAULT_SCALE_LJ_14);
        expect_miss("1-4 scales swapped", &swapped, "coulomb");
        expect_miss("1-4 scales swapped", &swapped, "lj");

        let (a, b) = most_different(&top.charges);
        let mut qswap = top.clone();
        qswap.charges.swap(a, b);
        expect_miss(&format!("charges {a}<->{b} swapped"), &qswap, "coulomb");

        let sigmas: Vec<f64> = top.lj.iter().map(|p| p.sigma).collect();
        let (a, b) = most_different(&sigmas);
        let mut ljswap = top.clone();
        ljswap.lj.swap(a, b);
        expect_miss(&format!("LJ {a}<->{b} swapped"), &ljswap, "lj");

        let mut neg = top.clone();
        neg.torsions.iter_mut().for_each(|d| d.phase = -d.phase);
        if phases_even {
            // The blind spot, asserted: phases 0/180 make the torsion energy
            // even in phi, so a dihedral sign error is invisible here.
            let d = control_rel(&neg, &x, "torsion", e_ref("torsion"), ke);
            assert!(
                d < TOL_E_REL,
                "{tag}: negating 0/180-degree phases moved the torsion energy ({d:.3e})"
            );
        } else {
            expect_miss("torsion phases negated", &neg, "torsion");
        }
    }

    eprintln!(
        "MEASURED {sys}: max dE_rel {:.2e}, max dG_rel {:.2e}, decomposition {:.2e}, \
         Coulomb-offset residual {:.2e}, smallest control gap {:.2e}",
        w.e, w.g, w.decomp, w.ke_offset, w.min_control_gap
    );
}

/// The index pair with the largest |v[a] - v[b]| (first found on ties).
fn most_different(v: &[f64]) -> (usize, usize) {
    let (mut lo, mut hi) = (0, 0);
    for (i, &x) in v.iter().enumerate() {
        if x < v[lo] {
            lo = i;
        }
        if x > v[hi] {
            hi = i;
        }
    }
    assert!(
        v[hi] > v[lo],
        "all values equal; the swap control would be a no-op"
    );
    (lo.min(hi), lo.max(hi))
}

