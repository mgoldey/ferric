fn workspace_root() -> PathBuf {
    let looks_like_root = |p: &Path| {
        p.join("Cargo.toml").is_file() && p.join("testdata").is_dir() && p.join("crates").is_dir()
    };
    if let Ok(cwd) = std::env::current_dir() {
        let mut here: Option<&Path> = Some(cwd.as_path());
        while let Some(p) = here {
            if looks_like_root(p) {
                return p.to_path_buf();
            }
            here = p.parent();
        }
    }
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(|p| p.parent())
        .expect("ferric-mm manifest dir should be <root>/crates/ferric-mm")
        .to_path_buf()
}

fn reference(system: &str) -> Value {
    let path = workspace_root()
        .join(ROW_DIR)
        .join(format!("{system}.json"));
    let text = std::fs::read_to_string(&path).unwrap_or_else(|e| {
        panic!(
            "missing validation reference {} ({e}); regenerate with \
             scripts/validation/gen_mm.py — a missing reference is a failure, never a skip",
            path.display()
        )
    });
    serde_json::from_str(&text).unwrap_or_else(|e| panic!("{}: bad JSON: {e}", path.display()))
}

fn num(v: &Value, ptr: &str) -> f64 {
    v.pointer(ptr)
        .and_then(Value::as_f64)
        .unwrap_or_else(|| panic!("reference field {ptr} missing or not a number"))
}

fn arr<'a>(v: &'a Value, ptr: &str) -> &'a Vec<Value> {
    v.pointer(ptr)
        .and_then(Value::as_array)
        .unwrap_or_else(|| panic!("reference field {ptr} missing or not an array"))
}

fn f64s(v: &Value) -> Vec<f64> {
    v.as_array()
        .expect("number array")
        .iter()
        .map(|x| x.as_f64().expect("number"))
        .collect()
}

fn idx(v: &Value) -> usize {
    v.as_u64().expect("index") as usize
}

fn rows(v: &Value) -> Array2<f64> {
    let r = v.as_array().expect("rows");
    let mut out = Array2::<f64>::zeros((r.len(), 3));
    for (i, row) in r.iter().enumerate() {
        let x = f64s(row);
        assert_eq!(x.len(), 3, "coordinate/gradient row of length {}", x.len());
        for (c, v) in x.into_iter().enumerate() {
            out[(i, c)] = v;
        }
    }
    out
}

fn pair_set(v: &Value, ptr: &str) -> HashSet<(usize, usize)> {
    arr(v, ptr)
        .iter()
        .map(|p| {
            let p = p.as_array().expect("pair");
            (idx(&p[0]), idx(&p[1]))
        })
        .collect()
}

/// The production path: `topology_from_system`'s dict -> `from_amber_units`.
fn build_topology(r: &Value) -> MmTopology {
    let t = &r["topology"];
    let charges = f64s(&t["charges"]);
    let lj: Vec<(f64, f64)> = f64s(&t["sigmas_angstrom"])
        .into_iter()
        .zip(f64s(&t["epsilons_kcal"]))
        .collect();
    let bonds = arr(t, "/bonds")
        .iter()
        .map(|b| {
            let b = b.as_array().unwrap();
            (
                idx(&b[0]),
                idx(&b[1]),
                b[2].as_f64().unwrap(),
                b[3].as_f64().unwrap(),
            )
        })
        .collect();
    let angles = arr(t, "/angles")
        .iter()
        .map(|a| {
            let a = a.as_array().unwrap();
            (
                idx(&a[0]),
                idx(&a[1]),
                idx(&a[2]),
                a[3].as_f64().unwrap(),
                a[4].as_f64().unwrap(),
            )
        })
        .collect();
    let torsions = arr(t, "/torsions")
        .iter()
        .map(|d| {
            let d = d.as_array().unwrap();
            (
                idx(&d[0]),
                idx(&d[1]),
                idx(&d[2]),
                idx(&d[3]),
                d[4].as_u64().unwrap() as u32,
                d[5].as_f64().unwrap(),
                d[6].as_f64().unwrap(),
            )
        })
        .collect();
    MmTopology::from_amber_units(charges, lj, bonds, angles, torsions)
        .expect("from_amber_units on the exported ff14SB topology")
}

fn coords_bohr(geom: &Value) -> Array2<f64> {
    rows(&geom["coords_angstrom"]) * ANGSTROM_TO_BOHR
}

