//! VALIDATION tier — VALIDATION.md row "ferric-mm vs OpenMM".
//!
//! Runs only in the weekly `validation` CI job (and on demand):
//!
//! ```text
//! cargo nextest run -p ferric-mm --test validation_mm \
//!     --run-ignored only -E 'binary(/^validation_/)'
//! ```
//!
//! # What is compared
//!
//! `ferric_mm::gradient` (AMBER-form bonds, angles, periodic torsions,
//! Lorentz-Berthelot LJ, bare Coulomb, bond-graph exclusions, global 1-4
//! scaling; no cutoff, no periodicity) against OpenMM 8.6's Reference platform
//! (double precision) on REAL ff14SB / TIP3P parameters. References:
//! `testdata/reference/validation/mm/*.json`, generated by
//! `scripts/validation/gen_mm.py`. The parameters in each JSON are the output
//! of `tools/active_site/mm_topology.py::topology_from_system` (the production
//! extraction code) and go through `MmTopology::from_amber_units` here, the
//! same path the Python `MmTopology` takes. ferric derives its OWN exclusions
//! and 1-4 pairs from the bond list; OpenMM uses the force field's per-pair
//! exceptions, which the JSON also carries so the two pair sets are compared
//! directly.
//!
//! | system | atoms | what it exercises |
//! |---|---|---|
//! | `ala_ala` | 23 | zwitterionic ALA-ALA (`tools/active_site/tests/ala_ala.pdb`) |
//! | `ace_phe_nme` | 32 | capped dipeptide; 6-ring (para 1-4, meta excluded) |
//! | `trp_pro_asp` | 53 | zwitterion, net charge -1; fused indole bicycle, proline 5-ring |
//! | `ace_phe_nme_3wat` | 41 | + 3 flexible TIP3P waters (H eps = 0, intermolecular pairs) |
//! | `ace_phe_nme_phase37` | 32 | SYNTHETIC: every torsion phase + 37 degrees |
//!
//! Each system is evaluated at three geometries: the committed PDB (relaxed,
//! near a minimum) and two seeded random perturbations (sigma 0.03 and
//! 0.10 Angstrom per component; max |dE/dR| up to 0.56 Ha/Bohr).
//!
//! Per term (bond, angle, torsion, coulomb, lj) and for the total: the energy
//! and the gradient on every atom. ferric returns one combined gradient, so a
//! per-term ferric gradient is taken from a copy of the topology with every
//! other term switched off (other lists emptied, charges or epsilons zeroed;
//! bonds are kept with k = 0 wherever the exclusions must survive), and the
//! per-term gradients are asserted to sum to the full `gradient()` output.
//!
//! # The Coulomb constant
//!
//! ferric's Coulomb constant is exactly 1 Hartree*Bohr. OpenMM's
//! e^2/(4 pi eps0) = 138.93545764438198 kJ/mol*nm (CODATA 2018) converted with
//! ferric's own constants (4.184 kJ/kcal, 627.509474 kcal/mol/Ha,
//! 0.52917721092 A/Bohr) is 1 + 6.62e-11. So every reference Coulomb energy and
//! force is larger than ferric's by that ratio (the generator measures it and
//! records it as `provenance.coulomb_constant.openmm_in_hartree_bohr`). This
//! test (a) asserts that the RAW Coulomb disagreement IS that offset, to
//! `TOL_E_REL`, and (b) multiplies ferric's Coulomb energy and gradient by the
//! ratio before every other comparison, so the remaining bars are set by
//! arithmetic, not by a constants mismatch.
//!
//! # Physics hypothesis vs artifact hypothesis
//!
//! * If ferric-mm is right: every term agrees at double-precision roundoff
//!   (a numpy transcription of `energy.rs` fed the same JSON reproduces the
//!   reference energies to <= 6.5e-13 relative per term), and the pair sets
//!   are identical.
//! * If a 1-4 scale is wrong (swapped, or 1): Coulomb and LJ both move by
//!   percent-level amounts. Controls 1 and 2.
//! * If a parameter reaches the wrong atom (an index/ordering slip in the
//!   extraction or in `from_amber_units`): the charge-swap and LJ-swap
//!   controls show the size of such a slip.
//! * If the combining rule were geometric instead of Lorentz for sigma: not
//!   expressible in the input; it is the documented MUTATION below.
//! * If the dihedral sign convention were flipped: ff14SB phases are all 0 or
//!   180 degrees, where cos(n*phi - delta) is even in phi, so the four real
//!   systems CANNOT see it (asserted: negating every phase leaves their
//!   torsion energy unchanged). `ace_phe_nme_phase37` exists for this; there
//!   the negated-phase control must miss.
//! * If the harness is broken (wrong file, units, atom order): the
//!   exclusion/1-4 set comparison and the bond term fail first.
//!
//! # NEGATIVE CONTROLS (at every geometry of every system; each edits the INPUT
//! topology, so it runs through ferric's real code path)
//!
//! 1. `with_scales(1.0, 1.0)` (1-4 pairs unscaled): Coulomb AND LJ must miss.
//! 2. scales swapped, `with_scales(1/1.2, 0.5)`: Coulomb AND LJ must miss.
//! 3. the charges of the two atoms with the most different charges swapped:
//!    Coulomb must miss.
//! 4. the LJ (sigma, epsilon) of the two atoms with the most different sigma
//!    swapped: LJ must miss.
//! 5. every torsion phase negated: must MISS on `ace_phe_nme_phase37`, must
//!    NOT move the torsion energy on the ff14SB systems (the blind spot).
//!
//! "Miss" = relative error above `MISS_FACTOR` x the bar.
//!
//! # MUTATIONS (each must turn a test red)
//!
//! Run 2026-09-25; each mutation turned every listed test red.
//!
//! * `crates/ferric-mm/src/energy.rs`, `mix()`:
//!   `sigma: 0.5 * (a.sigma + b.sigma),` -> `sigma: (a.sigma * b.sigma).sqrt(),`
//!   (geometric sigma combining rule) -> the LJ energy of every system misses.
//! * `crates/ferric-mm/src/energy.rs`, `dihedral_and_gradient()`:
//!   `if dot(r_ij, n) < 0.0 {` -> `if dot(r_ij, n) > 0.0 {` (flipped dihedral
//!   sign) -> all five systems fail: the torsion GRADIENT flips sign
//!   (relative error 2.0) wherever a torsion is off 0°/180°, although the
//!   torsion ENERGY of the four ff14SB systems cannot see it (the blind spot
//!   above; only `ace_phe_nme_phase37` misses in the energy).
//! * `crates/ferric-mm/src/topology.rs`:
//!   `DEFAULT_SCALE_COUL_14: f64 = 1.0 / 1.2;` -> `0.5` -> every system fails
//!   (the scale check and the Coulomb term).
//!
//! A missing reference JSON is a HARD failure (panic naming the path).

use std::collections::HashSet;
use std::path::{Path, PathBuf};

use ferric_mm::topology::{DEFAULT_SCALE_COUL_14, DEFAULT_SCALE_LJ_14};
use ferric_mm::{energy, gradient, MmTopology};
use ndarray::Array2;
use serde_json::Value;

const ROW_DIR: &str = "testdata/reference/validation/mm";

/// ferric's Å -> Bohr (crates/ferric-mm/src/units.rs).
const ANGSTROM_TO_BOHR: f64 = 1.0 / 0.529_177_210_92;

/// Per-term energy, relative to |E_ref| (total: relative to the sum of the
/// |per-term| reference energies, since the total is a cancellation). After
/// the Coulomb-constant rescaling.
// Measured max 1.75e-12 (ace_phe_nme).
const TOL_E_REL: f64 = 1e-11;
/// Per-term gradient: max |dg| over all atoms and components, relative to the
/// max |g_ref| of that term. After the Coulomb-constant rescaling.
// Measured max 8.5e-11 (ace_phe_nme).
const TOL_G_REL: f64 = 1e-9;
/// Sum of ferric's per-term gradients vs its full `gradient()` (same code,
/// different summation order), relative to max |g|.
// Measured max 1.6e-14 (trp_pro_asp).
const TOL_DECOMP_REL: f64 = 1e-13;
/// OpenMM's 1-4 scales, measured from its exceptions, vs ferric's defaults.
const TOL_SCALE: f64 = 1e-14;
/// A control must miss by this multiple of the bar it is judged against.
const MISS_FACTOR: f64 = 100.0;

const TERMS: [&str; 5] = ["bond", "angle", "torsion", "coulomb", "lj"];

