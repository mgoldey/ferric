// ferric side: per-term energies and gradients
// ---------------------------------------------------------------------------

/// A copy of `top` in which only `term` is live. Bonds stay (with k = 0 when
/// the bond term itself is off) so the derived exclusions/1-4 pairs survive.
fn only(top: &MmTopology, term: &str) -> MmTopology {
    let mut t = top.clone();
    if term != "bond" {
        for b in &mut t.bonds {
            b.k = 0.0;
        }
    }
    if term != "angle" {
        t.angles.clear();
    }
    if term != "torsion" {
        t.torsions.clear();
    }
    if term != "coulomb" {
        t.charges.iter_mut().for_each(|q| *q = 0.0);
    }
    if term != "lj" {
        t.lj.iter_mut().for_each(|p| p.epsilon = 0.0);
    }
    t
}

fn term_energy(e: &ferric_mm::MmEnergy, term: &str) -> f64 {
    match term {
        "bond" => e.bond,
        "angle" => e.angle,
        "torsion" => e.torsion,
        "coulomb" => e.coulomb,
        "lj" => e.lj,
        "total" => e.total,
        _ => unreachable!(),
    }
}

fn max_abs(a: &Array2<f64>) -> f64 {
    a.iter().fold(0.0_f64, |m, x| m.max(x.abs()))
}

fn rel_e(e: f64, e_ref: f64) -> f64 {
    (e - e_ref).abs() / e_ref.abs().max(1e-300)
}

fn rel_g(g: &Array2<f64>, g_ref: &Array2<f64>) -> f64 {
    max_abs(&(g - g_ref)) / max_abs(g_ref).max(1e-300)
}

/// Energy of one term with ferric's Coulomb constant replaced by OpenMM's.
fn ferric_term_energy(top: &MmTopology, x: &Array2<f64>, term: &str, ke: f64) -> f64 {
    let e = energy(top, x).unwrap();
    let v = term_energy(&e, term);
    if term == "coulomb" {
        v * ke
    } else {
        v
    }
}

