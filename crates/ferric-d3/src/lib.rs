//! Grimme D3 dispersion with Becke-Johnson damping, implemented natively in Rust.
//!
//! DFT with a semilocal functional has no long-range correlation, so it misses
//! London dispersion entirely. D3(BJ) adds it back as a parameterised pairwise
//! sum over atoms. It is the dominant attractive term in ligand binding and in
//! any halogen or CF3 substituent comparison, so a "DFT" energy without it is
//! not comparable between conformers or between substituents.
//!
//! # The model
//!
//! ```text
//! E_disp = - sum_{A<B} [ s6 * C6_AB / (R_AB^6 + f(R0_AB)^6)
//!                      + s8 * C8_AB / (R_AB^8 + f(R0_AB)^8) ]
//! ```
//!
//! with the Becke-Johnson rational damping radius `f(R0) = a1 * R0_AB + a2`
//! and `R0_AB = sqrt(C8_AB / C6_AB)`.
//!
//! `C6_AB` is not a constant: it is interpolated from tabulated reference
//! values by the two atoms' **coordination numbers**, which is what makes D3
//! sensitive to hybridisation (an sp3 carbon and an sp2 carbon get different
//! C6). The coordination number is a smooth, differentiable count,
//!
//! ```text
//! CN_A = sum_{B != A} 1 / (1 + exp(-k * ((Rcov_A + Rcov_B) / R_AB - 1)))
//! ```
//!
//! and the reference interpolation is a Gaussian weighting in `CN`:
//!
//! ```text
//! C6_AB(CN_A, CN_B) = sum_{i,j} C6ref_ij * W_i(CN_A) * W_j(CN_B) / sum_{i,j} W_i W_j
//! W_i(CN) = exp(-wf * (CN - CNref_i)^2)
//! ```
//!
//! `C8_AB = 3 * C6_AB * sqrt(Q_A * Q_B)` with `Q_A = sqrt(Z_A) * <r^4>/<r^2>_A / 2`.
//!
//! # Three-body term (Axilrod-Teller-Muto, `s9`)
//!
//! With `D3Params::s9 != 0` the energy gains the ATM term
//!
//! ```text
//! E_ATM = s9 * sum_{A>B>C} sqrt(C6_AB C6_AC C6_BC) * fdmp * (3 cos(a) cos(b) cos(c) + 1) / (R_AB R_BC R_AC)^3
//! fdmp  = 1 / (1 + 6 (r0 / (R_AB R_BC R_AC))^(16/3)),   r0 = prod over the 3 pairs of (4/3) R0vdw_pair
//! ```
//!
//! exactly as simple-dftd3 defines it for rational damping: zero damping with
//! `rs9 = 4/3` ([`ATM_RS9`]), exponent `alp + 2 = 16` ([`ATM_ALPHA`]), the
//! tabulated pairwise vdW radii (`tables::VDW_RAD`), and the CN-dependent
//! `C6` of the two-body term. The BJ `a1`/`a2` do not enter. The gradient
//! includes the CN chain rule through all three `C6`.
//!
//! **Default: off.** [`d3bj_params_for_functional`] returns `s9 = 0.0`, which
//! is what the references use for a named functional (simple-dftd3 CLI without
//! `--atm`, its API `load_rational_damping(atm=False)`, Grimme's `dftd3`
//! without `-abc`). `s9 = 0.0` skips the triple sum entirely, so the two-body
//! energy and gradient are bit-for-bit unchanged. Only simple-dftd3's
//! explicit-parameter constructor defaults to `s9 = 1.0`.
//!
//! Differences from the reference: no real-space cutoff (simple-dftd3 drops
//! triples with any distance > 40 Bohr and pairs > 60 Bohr; ferric sums all),
//! and the triple sum is O(N^3).
//!
//! Measured size of the three-body term (simple-dftd3 1.6.0, independent of
//! the functional's BJ parameters): water 2.3e-10 Ha, methane 3.6e-8, water
//! dimer 5.1e-7, benzene 9.4e-6 Ha (0.10 % of the PBE0 two-body energy).
//!
//! # Scope
//!
//! Implemented and validated: the two-body D3(BJ) energy and, optionally, the
//! ATM three-body term, for elements Z = 1..103, any molecular geometry, and
//! the analytic nuclear gradient of both ([`d3bj_gradient`],
//! [`d3bj_gradient_for_molecule`]) including the coordination-number chain
//! rule. The CLI uses it for `task = "optimize"` with `[dft] dispersion`;
//! `task = "frequencies"` is refused (the finite-difference Hessian built from
//! it is unvalidated). The CLI and the DFT-path `dispersion=` option use the
//! named-functional parameters and therefore `s9 = 0`; the standalone Python
//! `d3bj_energy(mol, functional, s9=...)` exposes `s9`.
//!
//! NOT implemented: zero damping for the two-body term, second derivatives,
//! and periodic boundary conditions.
//!
//! # Provenance of the reference data
//!
//! `tables.rs` is GENERATED by `generate_tables.py` from the upstream
//! s-dftd3 Fortran (<https://github.com/dftd3/simple-dftd3>, LGPL-3.0-or-later),
//! which in turn carries the data published in Grimme et al., JCP 132, 154104
//! (2010) and the BJ-damping paper JCC 32, 1456 (2011). Nothing is
//! hand-transcribed.
//!
//! # Validation
//!
//! MEASURED against the `dftd3` Python package (simple-dftd3 1.6.0) -- an
//! INDEPENDENT implementation, not the source of this code's arithmetic:
//!
//! - two-body energy on water, methane, water dimer, Br2, benzene and an argon
//!   dimer, 4 functionals, < 1e-12 Ha (`tests/vs_reference_dftd3.rs`);
//! - energy and gradient with `s9 = 0` and `s9 = 1` on those systems plus an
//!   argon trimer, a C/F/O/N/H fragment and CHBr3, 3 functionals: worst
//!   1.2e-13 Ha and 5.5e-13 Ha/Bohr on totals, 2.6e-15 Ha and 5.9e-16 Ha/Bohr
//!   on the isolated three-body part (`tests/vs_reference_dftd3_atm.rs`,
//!   reference written by `scripts/gen_d3_atm_reference.py`).
//!
//! The analytic gradient also matches central finite differences of
//! [`d3bj_energy`]: two-body and full to 1e-7 Ha/Bohr, the three-body term
//! alone to 1e-7 relative (`tests/gradient_vs_fd.rs`).

pub mod params;
pub mod tables;

pub use params::{d3bj_params_for_functional, D3Params};

use ferric_core::FerricError;

/// Steepness of the coordination-number counting function (upstream `default_kcn`).
const KCN: f64 = 16.0;
/// Gaussian weighting factor for the reference interpolation (upstream `wf_default`).
const WF: f64 = 4.0;
/// Angstrom -> Bohr. Matches upstream mctc-lib's `aatoau` (= ferric's
/// one conversion, [`ferric_core::units::ANGSTROM_TO_BOHR`]).
const AA_TO_AU: f64 = ferric_core::units::ANGSTROM_TO_BOHR;
/// Upstream scales the 2009 covalent radii by 4/3 to build the D3 CN.
const COV_SCALE: f64 = 4.0 / 3.0;
/// Scale of the pairwise vdW radius in the three-body damping (upstream
/// `rs9` in `damping/rational.f90`).
pub const ATM_RS9: f64 = 4.0 / 3.0;
/// Exponent of the three-body zero damping: upstream passes `alp + 2` with the
/// rational-damping default `alp = 14`.
pub const ATM_ALPHA: f64 = 16.0;

/// Covalent radius used by the coordination-number counting function, in Bohr.
fn rcov(z: usize) -> f64 {
    COV_SCALE * AA_TO_AU * tables::COVALENT_RAD[z - 1]
}

/// `Q_A = sqrt(Z) * <r^4>/<r^2> / 2`, the per-element factor in `C8 = 3 C6 sqrt(Q_A Q_B)`.
///
/// Upstream folds this into `sqrt_z_r4_over_r2` as `sqrt(0.5 * r4r2 * sqrt(Z))`;
/// that stored quantity is `sqrt(Q)`, so `C8 = 3 * C6 * sqrt(Q_A) * sqrt(Q_B)`
/// there. Here the square root is taken once, at the same place, so the two
/// forms are algebraically identical.
fn sqrt_q(z: usize) -> f64 {
    (0.5 * tables::R4R2[z - 1] * (z as f64).sqrt()).sqrt()
}

/// Packed lower-triangular index for an element pair, matching upstream's
/// `get_c6` addressing.
///
/// Returns the flat pair index and whether the (iref, jref) axes must be
/// swapped, because upstream stores only one triangle.
fn pair_index(zi: usize, zj: usize) -> (usize, bool) {
    if zi > zj {
        (zj + zi * (zi - 1) / 2 - 1, false)
    } else {
        (zi + zj * (zj - 1) / 2 - 1, true)
    }
}

/// A tabulated reference C6 for a given pair of reference systems.
fn reference_c6(iref: usize, jref: usize, zi: usize, zj: usize) -> f64 {
    let (ic, swap) = pair_index(zi, zj);
    let (a, b) = if swap { (jref, iref) } else { (iref, jref) };
    tables::REFERENCE_C6[a + tables::MAX_REF * (b + tables::MAX_REF * ic)]
}

/// Validate atomic numbers and return them as `usize`, erroring on anything
/// outside the D3 parameterisation.
///
/// This is deliberately an error and not a skip: silently dropping an
/// unparameterised atom would return a smaller-magnitude dispersion energy
/// that still looks like a number, which is exactly the fabricated-neutral
/// value this repo's conventions forbid.
fn checked_numbers(numbers: &[u8]) -> Result<Vec<usize>, FerricError> {
    numbers
        .iter()
        .map(|&z| {
            let z = z as usize;
            if z == 0 || z > tables::MAX_ELEM {
                Err(FerricError::General(format!(
                    "D3 dispersion has no reference data for atomic number {z}; \
                     the D3 parameterisation covers Z = 1..{}. Refusing to return a \
                     dispersion energy that silently omits this atom.",
                    tables::MAX_ELEM
                )))
            } else {
                Ok(z)
            }
        })
        .collect()
}

/// Smooth, differentiable coordination numbers for every atom.
///
/// `CN_A = sum_{B != A} 1 / (1 + exp(-k ((Rcov_A + Rcov_B)/R_AB - 1)))`
fn coordination_numbers(z: &[usize], coords: &[[f64; 3]]) -> Vec<f64> {
    let n = z.len();
    let mut cn = vec![0.0; n];
    for i in 0..n {
        for j in 0..i {
            let r = distance(&coords[i], &coords[j]);
            // A zero separation would divide by zero; two atoms on top of each
            // other is a broken geometry, so saturate the count rather than
            // producing a NaN that propagates silently into the energy.
            let count = if r <= f64::EPSILON {
                1.0
            } else {
                let rc = rcov(z[i]) + rcov(z[j]);
                1.0 / (1.0 + (-KCN * (rc / r - 1.0)).exp())
            };
            cn[i] += count;
            cn[j] += count;
        }
    }
    cn
}

fn distance(a: &[f64; 3], b: &[f64; 3]) -> f64 {
    let (dx, dy, dz) = (a[0] - b[0], a[1] - b[1], a[2] - b[2]);
    (dx * dx + dy * dy + dz * dz).sqrt()
}

/// Gaussian weights over an element's reference systems at a given CN.
///
/// Returned unnormalised; the normalisation cancels in the C6 interpolation
/// only if it is applied to both the numerator and denominator, so it is done
/// explicitly by the caller.
fn reference_weights(z: usize, cn: f64) -> Vec<f64> {
    let nref = tables::NUMBER_OF_REFERENCES[z - 1] as usize;
    (0..nref)
        .map(|iref| {
            let cnref = tables::REFERENCE_CN[iref + tables::MAX_REF * (z - 1)];
            let d = cn - cnref;
            (-WF * d * d).exp()
        })
        .collect()
}

/// Interpolated `C6_AB` at the two atoms' coordination numbers.
fn c6_interpolated(zi: usize, zj: usize, cni: f64, cnj: f64) -> f64 {
    let wi = reference_weights(zi, cni);
    let wj = reference_weights(zj, cnj);
    let mut num = 0.0;
    let mut den = 0.0;
    for (iref, &a) in wi.iter().enumerate() {
        for (jref, &b) in wj.iter().enumerate() {
            let w = a * b;
            num += reference_c6(iref, jref, zi, zj) * w;
            den += w;
        }
    }
    // Far from every reference CN all weights underflow to zero. Upstream
    // handles this by falling back to the nearest reference; here the
    // denominator guard keeps the result finite rather than NaN.
    if den > 1e-300 {
        num / den
    } else {
        // Nearest-reference fallback: pick the single closest reference CN on
        // each side. This is the wf -> infinity limit of the same expression.
        let near = |z: usize, cn: f64| {
            let nref = tables::NUMBER_OF_REFERENCES[z - 1] as usize;
            (0..nref)
                .min_by(|&a, &b| {
                    let da = (cn - tables::REFERENCE_CN[a + tables::MAX_REF * (z - 1)]).abs();
                    let db = (cn - tables::REFERENCE_CN[b + tables::MAX_REF * (z - 1)]).abs();
                    da.partial_cmp(&db).unwrap_or(std::cmp::Ordering::Equal)
                })
                .unwrap_or(0)
        };
        reference_c6(near(zi, cni), near(zj, cnj), zi, zj)
    }
}

/// D3(BJ) dispersion energy, in Hartree: the two-body term, plus the ATM
/// three-body term when `params.s9 != 0`.
///
/// `numbers` are atomic numbers, `coords` are Cartesian coordinates in **Bohr**
/// (ferric's internal convention -- see `ferric_core::Molecule`).
///
/// Returns an error rather than a number if any atom lies outside the D3
/// parameterisation, if `numbers` and `coords` disagree in length, or if two
/// atoms sit at the same position.
///
/// Fewer than two atoms returns `Ok(0.0)`, which is exact rather than a
/// fallback: the two-body sum runs over pairs and there are none. A caller for
/// which an empty input is a MISTAKE rather than a zero-dispersion system must
/// reject it before calling -- `d3bj_energy_for_molecule` does exactly that for
/// a molecule of only ghost centres.
pub fn d3bj_energy(
    numbers: &[u8],
    coords: &[[f64; 3]],
    params: &D3Params,
) -> Result<f64, FerricError> {
    if numbers.len() != coords.len() {
        return Err(FerricError::General(format!(
            "D3: {} atomic numbers but {} coordinates",
            numbers.len(),
            coords.len()
        )));
    }
    // Non-finite coordinates must be REFUSED, not propagated.
    //
    // MEASURED before this guard: a NaN coordinate returned `Ok(NaN)`, and an
    // INFINITE one returned `Ok(0.0)` -- a clean-looking zero dispersion
    // energy from a broken geometry. The zero is the dangerous one: NaN at
    // least propagates visibly into whatever consumes it, while 0.0 is
    // indistinguishable from "computed, and the atoms are far apart".
    //
    // Reachable from an optimizer that took a bad step, or from a coordinate
    // read through a failed unit conversion.
    for (i, c) in coords.iter().enumerate() {
        if !c.iter().all(|v| v.is_finite()) {
            return Err(FerricError::General(format!(
                "D3: atom {i} has a non-finite coordinate {c:?}. An infinite \
                 separation would return a clean 0.0, which is indistinguishable \
                 from a computed answer."
            )));
        }
    }
    let z = checked_numbers(numbers)?;
    let n = z.len();
    if n < 2 {
        // Fewer than two atoms means no PAIRS, so the two-body sum is empty.
        // An empty sum is exactly 0.0 -- arithmetic, not a fallback, and this
        // primitive keeps that identity (pinned by exactness_anchor.rs).
        //
        // Whether an empty input is MEANINGFUL is a caller question, not an
        // arithmetic one, so it is answered one level up: see
        // `d3bj_energy_for_molecule`, which rejects a molecule whose atoms are
        // all ghosts because that is a configuration mistake rather than a
        // zero-dispersion system.
        return Ok(0.0);
    }

    let cn = coordination_numbers(&z, coords);

    let mut energy = 0.0;
    for i in 0..n {
        for j in 0..i {
            let r = distance(&coords[i], &coords[j]);
            if r <= f64::EPSILON {
                return Err(FerricError::General(format!(
                    "D3: atoms {i} and {j} are at the same position; \
                     the dispersion energy diverges."
                )));
            }
            let c6 = c6_interpolated(z[i], z[j], cn[i], cn[j]);
            // C8 = 3 C6 sqrt(Q_A Q_B), and R0 = sqrt(C8/C6) = sqrt(3 sqrt(Q_A Q_B)).
            let qq = sqrt_q(z[i]) * sqrt_q(z[j]);
            let c8 = 3.0 * c6 * qq;
            let r0 = (c8 / c6).sqrt();

            let f = params.a1 * r0 + params.a2;
            let f2 = f * f;
            let f6 = f2 * f2 * f2;
            let f8 = f6 * f2;

            let r2 = r * r;
            let r6 = r2 * r2 * r2;
            let r8 = r6 * r2;

            energy -= params.s6 * c6 / (r6 + f6) + params.s8 * c8 / (r8 + f8);
        }
    }
    if params.s9 != 0.0 {
        // Coincident atoms were rejected by the pair loop above, so every
        // distance in the triple sum is nonzero.
        energy += atm_energy(&z, coords, &cn, params.s9);
    }
    Ok(energy)
}

/// Analytic nuclear gradient of [`d3bj_energy`] (two-body, plus three-body
/// when `params.s9 != 0`), `dE/dR` in
/// Hartree/Bohr, as `n_atoms` rows of `[x, y, z]`.
///
/// # Why this is not just the pairwise derivative
///
/// `C6_AB` is **not a constant**: it is interpolated from reference values by
/// both atoms' coordination numbers, and every CN depends on every interatomic
/// distance. So moving atom `X` changes `C6_AB` for pairs that do not contain
/// `X` at all. The gradient therefore has two distinct parts:
///
/// ```text
/// dE/dR_X = [explicit]  the R^-6/R^-8 dependence of pairs containing X
///         + [CN chain]  sum_A (dE/dCN_A) (dCN_A/dR_X)
/// ```
///
/// Dropping the second part gives a gradient that looks right -- correct
/// magnitude, correct symmetry, smoothly varying -- and is wrong by a few
/// percent. It is caught only by finite difference, which is why
/// `tests/gradient_vs_fd.rs` exists and why it tests a system with mixed
/// coordination rather than a dimer (a dimer's CN term is small).
///
/// # What is NOT differentiated
///
/// The damping radius `f = a1*R0 + a2` with `R0 = sqrt(C8/C6) = sqrt(3*sqrt(QA*QB))`
/// depends only on the two ELEMENTS, never on geometry, so `df/dR = 0`. This
/// is a property of BJ damping, not an approximation: the `C6` in `C8 = 3*C6*q`
/// cancels in `C8/C6`. Verified in `damping_radius_is_geometry_independent`.
pub fn d3bj_gradient(
    numbers: &[u8],
    coords: &[[f64; 3]],
    params: &D3Params,
) -> Result<Vec<[f64; 3]>, FerricError> {
    if numbers.len() != coords.len() {
        return Err(FerricError::General(format!(
            "D3 gradient: {} atomic numbers but {} coordinates",
            numbers.len(),
            coords.len()
        )));
    }
    // Non-finite coordinates must be REFUSED, not propagated.
    //
    // MEASURED before this guard: a NaN coordinate returned `Ok(NaN)`, and an
    // INFINITE one returned `Ok(0.0)` -- a clean-looking zero dispersion
    // energy from a broken geometry. The zero is the dangerous one: NaN at
    // least propagates visibly into whatever consumes it, while 0.0 is
    // indistinguishable from "computed, and the atoms are far apart".
    //
    // Reachable from an optimizer that took a bad step, or from a coordinate
    // read through a failed unit conversion.
    for (i, c) in coords.iter().enumerate() {
        if !c.iter().all(|v| v.is_finite()) {
            return Err(FerricError::General(format!(
                "D3: atom {i} has a non-finite coordinate {c:?}. An infinite \
                 separation would return a clean 0.0, which is indistinguishable \
                 from a computed answer."
            )));
        }
    }
    let z = checked_numbers(numbers)?;
    let n = z.len();
    let mut grad = vec![[0.0f64; 3]; n];
    if n < 2 {
        // Same identity as the energy: no pairs, so the sum is empty and its
        // derivative is exactly zero. Not a fallback.
        return Ok(grad);
    }

    let cn = coordination_numbers(&z, coords);

    // dE/dCN_A, accumulated over every pair, then contracted with dCN_A/dR_X
    // in a second pass. Doing it in two passes rather than one is what keeps
    // this O(N^2) instead of O(N^3): the CN chain rule couples every pair to
    // every atom, but only through these n scalars.
    let mut de_dcn = vec![0.0f64; n];

    for i in 0..n {
        for j in 0..i {
            let r = distance(&coords[i], &coords[j]);
            if r <= f64::EPSILON {
                return Err(FerricError::General(format!(
                    "D3 gradient: atoms {i} and {j} are at the same position; \
                     the dispersion energy and its gradient diverge."
                )));
            }
            let c6 = c6_interpolated(z[i], z[j], cn[i], cn[j]);
            let qq = sqrt_q(z[i]) * sqrt_q(z[j]);
            let c8 = 3.0 * c6 * qq;
            // R0 = sqrt(C8/C6) = sqrt(3*qq): the C6 cancels, so this carries
            // no geometry dependence and contributes nothing to the gradient.
            let r0 = (3.0 * qq).sqrt();

            let f = params.a1 * r0 + params.a2;
            let f2 = f * f;
            let f6 = f2 * f2 * f2;
            let f8 = f6 * f2;

            let r2 = r * r;
            let r6 = r2 * r2 * r2;
            let r8 = r6 * r2;

            let d6 = r6 + f6;
            let d8 = r8 + f8;

            // --- explicit R dependence -------------------------------------
            // E_pair = -(s6 C6/d6 + s8 C8/d8), so
            // dE/dR = s6 C6 * 6 R^5 / d6^2 + s8 C8 * 8 R^7 / d8^2
            let r5 = r2 * r2 * r;
            let r7 = r5 * r2;
            let de_dr =
                params.s6 * c6 * 6.0 * r5 / (d6 * d6) + params.s8 * c8 * 8.0 * r7 / (d8 * d8);

            // dR/dx_i = (x_i - x_j)/R, and dR/dx_j is its negative.
            let inv_r = 1.0 / r;
            for a in 0..3 {
                let comp = (coords[i][a] - coords[j][a]) * inv_r * de_dr;
                grad[i][a] += comp;
                grad[j][a] -= comp;
            }

            // --- C6 dependence, banked for the CN pass ----------------------
            // dE_pair/dC6 = -(s6/d6 + 3 qq s8/d8), since C8 = 3 C6 qq is
            // itself linear in C6.
            let de_dc6 = -(params.s6 / d6 + 3.0 * qq * params.s8 / d8);
            let (dc6_di, dc6_dj) = c6_interpolated_derivatives(z[i], z[j], cn[i], cn[j]);
            de_dcn[i] += de_dc6 * dc6_di;
            de_dcn[j] += de_dc6 * dc6_dj;
        }
    }

    if params.s9 != 0.0 {
        // Adds the explicit three-body gradient into `grad` and banks the
        // three-body dE/dCN into `de_dcn`, so the contraction below carries
        // both terms' CN chain rule at once.
        atm_gradient(&z, coords, &cn, params.s9, &mut grad, &mut de_dcn);
    }

    // --- contract dE/dCN with dCN/dR ---------------------------------------
    //
    // CN_A = sum_{B != A} g(R_AB), and the SAME pair term appears in both CN_A
    // and CN_B, so a pair (i,j) contributes (de_dcn[i] + de_dcn[j]) * dg/dR.
    for i in 0..n {
        for j in 0..i {
            let r = distance(&coords[i], &coords[j]);
            if r <= f64::EPSILON {
                // Already rejected above; the counting function saturates here
                // and its derivative is zero, so skipping is consistent with
                // `coordination_numbers`.
                continue;
            }
            let rc = rcov(z[i]) + rcov(z[j]);
            // g = 1/(1+exp(-k(rc/R - 1)))  =>  dg/dR = -k rc/R^2 * g(1-g)
            let e = (-KCN * (rc / r - 1.0)).exp();
            let g = 1.0 / (1.0 + e);
            let dg_dr = -KCN * rc / (r * r) * g * (1.0 - g);

            let w = (de_dcn[i] + de_dcn[j]) * dg_dr;
            let inv_r = 1.0 / r;
            for a in 0..3 {
                let comp = (coords[i][a] - coords[j][a]) * inv_r * w;
                grad[i][a] += comp;
                grad[j][a] -= comp;
            }
        }
    }

    Ok(grad)
}

/// `dC6_AB/dCN_A` and `dC6_AB/dCN_B` at the given coordination numbers.
///
/// `C6 = N/D` with `N = sum_ij c_ij Wi Wj` and `D = sum_ij Wi Wj`, so by the
/// quotient rule `dC6/dCN_A = (dN/dCN_A - C6 dD/dCN_A)/D`. Written in that
/// form rather than as `(D dN - N dD)/D^2` because it reuses the already
/// computed `C6` and keeps one fewer large intermediate.
///
/// Returns `(0, 0)` in the underflow regime where `c6_interpolated` falls back
/// to the nearest reference: that branch is piecewise constant in CN, so its
/// derivative genuinely is zero almost everywhere. It is reached only far
/// outside the reference CN range.
fn c6_interpolated_derivatives(zi: usize, zj: usize, cni: f64, cnj: f64) -> (f64, f64) {
    let wi = reference_weights(zi, cni);
    let wj = reference_weights(zj, cnj);

    let mut num = 0.0;
    let mut den = 0.0;
    let mut dnum_i = 0.0;
    let mut dden_i = 0.0;
    let mut dnum_j = 0.0;
    let mut dden_j = 0.0;

    for (iref, &a) in wi.iter().enumerate() {
        // dWi/dCN_A = -2 wf (CN_A - CNref_i) Wi
        let cnref_i = tables::REFERENCE_CN[iref + tables::MAX_REF * (zi - 1)];
        let da = -2.0 * WF * (cni - cnref_i) * a;
        for (jref, &b) in wj.iter().enumerate() {
            let cnref_j = tables::REFERENCE_CN[jref + tables::MAX_REF * (zj - 1)];
            let db = -2.0 * WF * (cnj - cnref_j) * b;

            let c = reference_c6(iref, jref, zi, zj);
            num += c * a * b;
            den += a * b;
            dnum_i += c * da * b;
            dden_i += da * b;
            dnum_j += c * a * db;
            dden_j += a * db;
        }
    }

    if den > 1e-300 {
        let c6 = num / den;
        ((dnum_i - c6 * dden_i) / den, (dnum_j - c6 * dden_j) / den)
    } else {
        (0.0, 0.0)
    }
}

/// Pairwise vdW radius for the three-body damping, in Bohr (upstream
/// `get_vdw_rad`, packed like the C6 pair axis).
fn vdw_rad(zi: usize, zj: usize) -> f64 {
    AA_TO_AU * tables::VDW_RAD[pair_index(zi, zj).0]
}

/// Damped ATM geometry factor of one triple and its derivatives with respect
/// to the three SQUARED distances.
///
/// `x = R_ij^2`, `y = R_jk^2`, `w = R_ik^2`; `r0` is the product of the three
/// damping radii. Returns `(F, dF/dx, dF/dy, dF/dw)` with
///
/// ```text
/// F    = fdmp * ang
/// ang  = 3/8 (x+y-w)(x-y+w)(-x+y+w) / P^5 + 1/P^3,   P = R_ij R_jk R_ik
///      = (3 cos(a) cos(b) cos(c) + 1) / P^3
/// fdmp = 1 / (1 + 6 (r0/P)^(alpha/3))
/// ```
fn atm_triple_factor(x: f64, y: f64, w: f64, r0: f64) -> (f64, f64, f64, f64) {
    let p2 = x * y * w;
    let p = p2.sqrt();
    let p3 = p2 * p;
    let p5 = p3 * p2;
    // u, v, t are the three law-of-cosines numerators.
    let u = x + y - w;
    let v = x - y + w;
    let t = -x + y + w;
    let num = u * v * t;
    let ang = 0.375 * num / p5 + 1.0 / p3;
    let rr = (r0 / p).powf(ATM_ALPHA / 3.0);
    let fdmp = 1.0 / (1.0 + 6.0 * rr);
    // d/dq of each factor, for q in {x, y, w}, with dP/dq = P/(2q):
    //   d ang/dq  = 3/8 dN/dq / P^5 - 15/16 N/(q P^5) - 3/(2 q P^3)
    //   d fdmp/dq = alpha rr fdmp^2 / q
    let d = |q: f64, dnum: f64| {
        let dang = 0.375 * dnum / p5 - 0.9375 * num / (q * p5) - 1.5 / (q * p3);
        let dfdmp = ATM_ALPHA * rr * fdmp * fdmp / q;
        dang * fdmp + ang * dfdmp
    };
    // dN/dq by the product rule over (u, v, t).
    let dx = d(x, v * t + u * t - u * v);
    let dy = d(y, v * t - u * t + u * v);
    let dw = d(w, -v * t + u * t + u * v);
    (fdmp * ang, dx, dy, dw)
}

/// Interpolated C6 for every atom pair, as a dense `n x n` matrix.
fn c6_matrix(z: &[usize], cn: &[f64]) -> Vec<Vec<f64>> {
    let n = z.len();
    let mut c6 = vec![vec![0.0; n]; n];
    for i in 0..n {
        for j in 0..i {
            let c = c6_interpolated(z[i], z[j], cn[i], cn[j]);
            c6[i][j] = c;
            c6[j][i] = c;
        }
    }
    c6
}

/// Axilrod-Teller-Muto three-body energy, in Hartree, at scale `s9`.
///
/// ```text
/// E_ATM = s9 * sum_{i>j>k} sqrt(C6_ij C6_ik C6_jk) * F(R_ij, R_jk, R_ik)
/// ```
///
/// (upstream writes `C9 = -s9 sqrt(...)` and `E = -C9 F`). The damping radii
/// are `ATM_RS9 * R0vdw`, independent of the BJ `a1`/`a2`. Callers guarantee
/// every pair distance is nonzero.
fn atm_energy(z: &[usize], coords: &[[f64; 3]], cn: &[f64], s9: f64) -> f64 {
    let n = z.len();
    let c6 = c6_matrix(z, cn);
    let mut energy = 0.0;
    for i in 0..n {
        for j in 0..i {
            let x = dist2(&coords[i], &coords[j]);
            let r0ij = ATM_RS9 * vdw_rad(z[i], z[j]);
            for k in 0..j {
                let y = dist2(&coords[j], &coords[k]);
                let w = dist2(&coords[i], &coords[k]);
                let r0 = r0ij * ATM_RS9 * vdw_rad(z[j], z[k]) * ATM_RS9 * vdw_rad(z[i], z[k]);
                let c9 = (c6[i][j] * c6[i][k] * c6[j][k]).abs().sqrt();
                let (f, _, _, _) = atm_triple_factor(x, y, w, r0);
                energy += s9 * c9 * f;
            }
        }
    }
    energy
}

/// Adds the three-body term's explicit gradient to `grad` and its
/// `dE/dCN_A` to `de_dcn` (contracted with `dCN/dR` by the caller).
///
/// `E_t = s9 sqrt(C6_ij C6_ik C6_jk) F`, so `dE_t/dC6_ij = E_t / (2 C6_ij)`,
/// and `C6_ij` depends on `CN_i` and `CN_j`.
fn atm_gradient(
    z: &[usize],
    coords: &[[f64; 3]],
    cn: &[f64],
    s9: f64,
    grad: &mut [[f64; 3]],
    de_dcn: &mut [f64],
) {
    let n = z.len();
    let c6 = c6_matrix(z, cn);
    // dc6[a][b] = dC6_ab / dCN_a.
    let mut dc6 = vec![vec![0.0; n]; n];
    for i in 0..n {
        for j in 0..i {
            let (di, dj) = c6_interpolated_derivatives(z[i], z[j], cn[i], cn[j]);
            dc6[i][j] = di;
            dc6[j][i] = dj;
        }
    }
    // dE/d(R_ab^2) * d(R_ab^2)/dR_a, with d(R^2)/dR_a = 2 (R_a - R_b).
    let mut add_pair = |a: usize, b: usize, de_dq: f64| {
        for c in 0..3 {
            let comp = 2.0 * de_dq * (coords[a][c] - coords[b][c]);
            grad[a][c] += comp;
            grad[b][c] -= comp;
        }
    };
    for i in 0..n {
        for j in 0..i {
            let x = dist2(&coords[i], &coords[j]);
            let r0ij = ATM_RS9 * vdw_rad(z[i], z[j]);
            for k in 0..j {
                let y = dist2(&coords[j], &coords[k]);
                let w = dist2(&coords[i], &coords[k]);
                let r0 = r0ij * ATM_RS9 * vdw_rad(z[j], z[k]) * ATM_RS9 * vdw_rad(z[i], z[k]);
                let (cij, cjk, cik) = (c6[i][j], c6[j][k], c6[i][k]);
                let c9 = (cij * cik * cjk).abs().sqrt();
                let (f, dfx, dfy, dfw) = atm_triple_factor(x, y, w, r0);
                let scale = s9 * c9;
                add_pair(i, j, scale * dfx);
                add_pair(j, k, scale * dfy);
                add_pair(i, k, scale * dfw);

                // CN chain: dE_t/dC6_ab = E_t / (2 C6_ab).
                let half_e = 0.5 * scale * f;
                let (gij, gjk, gik) = (half_e / cij, half_e / cjk, half_e / cik);
                de_dcn[i] += gij * dc6[i][j] + gik * dc6[i][k];
                de_dcn[j] += gij * dc6[j][i] + gjk * dc6[j][k];
                de_dcn[k] += gik * dc6[k][i] + gjk * dc6[k][j];
            }
        }
    }
}

fn dist2(a: &[f64; 3], b: &[f64; 3]) -> f64 {
    let (dx, dy, dz) = (a[0] - b[0], a[1] - b[1], a[2] - b[2]);
    dx * dx + dy * dy + dz * dz
}

/// Analytic D3(BJ) gradient for a [`ferric_core::mol::Molecule`], in
/// Hartree/Bohr, with one row per atom **in the molecule's own order**.
///
/// Ghost centres are excluded from the dispersion sum for the same reason as
/// in the energy (no nucleus, no polarisable density), and their rows come
/// back as exact zeros. Getting that mapping right is the whole job of this
/// wrapper: `d3bj_gradient` sees only the filtered list, so its row `k` is not
/// atom `k` of the molecule whenever a ghost precedes it. Returning the
/// filtered vector directly would silently apply each force to the WRONG atom
/// -- a counterpoise geometry optimisation would then walk downhill on a
/// scrambled surface without any error.
pub fn d3bj_gradient_for_molecule(
    mol: &ferric_core::mol::Molecule,
    params: &D3Params,
) -> Result<Vec<[f64; 3]>, FerricError> {
    let real: Vec<usize> = (0..mol.atoms.len())
        .filter(|&i| !mol.atoms[i].ghost)
        .collect();
    let numbers: Vec<u8> = real.iter().map(|&i| mol.atoms[i].z as u8).collect();
    let coords: Vec<[f64; 3]> = real
        .iter()
        .map(|&i| [mol.atoms[i].x, mol.atoms[i].y, mol.atoms[i].zpos])
        .collect();

    // Same refusal as the energy: all-ghost is a configuration error, and a
    // zero gradient there would be indistinguishable from a computed one.
    if numbers.is_empty() && !mol.atoms.is_empty() {
        return Err(FerricError::General(format!(
            "D3 gradient: all {} centres in this molecule are ghosts, so there \
             are no real atoms to correct.",
            mol.atoms.len()
        )));
    }

    let filtered = d3bj_gradient(&numbers, &coords, params)?;
    let mut full = vec![[0.0f64; 3]; mol.atoms.len()];
    for (row, &iatom) in filtered.iter().zip(&real) {
        full[iatom] = *row;
    }
    Ok(full)
}

/// D3(BJ) energy (two-body, plus ATM when `params.s9 != 0`) for a
/// [`ferric_core::mol::Molecule`].
///
/// Convenience wrapper: ferric molecules already carry atomic numbers and
/// Bohr coordinates, so this is the form every caller inside ferric wants.
///
/// **Ghost atoms are excluded.** A ghost centre carries basis functions but no
/// nucleus and no electrons, so it has no polarisable density to disperse with.
/// Including one would add a spurious attraction and, in a counterpoise
/// calculation, would put dispersion energy on the very centres whose only job
/// is to supply basis functions -- turning a BSSE correction into a physics
/// error. ECP atoms ARE included at their full `z`, because the D3 reference
/// data is indexed by element, not by the number of explicitly treated
/// electrons.
pub fn d3bj_energy_for_molecule(
    mol: &ferric_core::mol::Molecule,
    params: &D3Params,
) -> Result<f64, FerricError> {
    let numbers: Vec<u8> = mol
        .atoms
        .iter()
        .filter(|a| !a.ghost)
        .map(|a| a.z as u8)
        .collect();
    let coords: Vec<[f64; 3]> = mol
        .atoms
        .iter()
        .filter(|a| !a.ghost)
        .map(|a| [a.x, a.y, a.zpos])
        .collect();
    // A molecule with atoms, ALL of which are ghosts, filters down to nothing.
    // `d3bj_energy` would correctly report the empty sum as 0.0, but at THIS
    // level that zero is indistinguishable from a computed correction, and it
    // is almost certainly a mis-specified counterpoise input rather than a
    // system anyone meant to correct. Refuse it here, where "all my atoms were
    // ghosts" is a statement that can be made.
    //
    // A genuinely empty molecule (no atoms at all) still returns 0.0 through
    // the primitive: there is nothing to warn anyone about.
    if numbers.is_empty() && !mol.atoms.is_empty() {
        return Err(FerricError::General(format!(
            "D3: all {} centres in this molecule are ghosts, so there are no              real atoms to correct. A ghost carries basis functions but no              nucleus, so this is a configuration error, not a zero dispersion              correction.",
            mol.atoms.len()
        )));
    }
    d3bj_energy(&numbers, &coords, params)
}

