#[test]
fn skeleton_is_symmetric_and_translationally_invariant() {
    if !has_deriv2() {
        return;
    }
    let fx = fixture(&mol_of(HO2_LIFTED, 2), "6-31g");
    let h = fx.parts.skeleton();
    let n3 = h.nrows();
    let asym = max_abs_diff(&h, &h.t().to_owned());
    eprintln!("skeleton asymmetry {asym:.3e}");
    assert!(asym < TOL_TRANSLATION, "skeleton not symmetric: {asym:.3e}");
    let mut worst = 0.0f64;
    for a in 0..n3 {
        for axis in 0..3 {
            let sum: f64 = (0..n3 / 3).map(|b| h[(a, 3 * b + axis)]).sum();
            worst = worst.max(sum.abs());
        }
    }
    eprintln!("translational invariance of the skeleton: worst row sum {worst:.3e}");
    assert!(worst < TOL_TRANSLATION, "row sum {worst:.3e}");
    assert!(
        max_abs(&fx.parts.two_electron) > 1.0,
        "vacuous: 2e skeleton is ~0"
    );
}

