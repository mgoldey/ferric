const ROW_DIR: &str = "testdata/reference/validation/rohf_hessian";
const MOL_DIR: &str = "testdata/molecules/validation";

fn workspace_root() -> PathBuf {
    let looks_like_root = |p: &Path| {
        p.join("Cargo.toml").is_file() && p.join("testdata").is_dir() && p.join("crates").is_dir()
    };
    if let Ok(cwd) = std::env::current_dir() {
        let mut here: Option<&Path> = Some(cwd.as_path());
        while let Some(p) = here {
            if looks_like_root(p) {
                return p.to_path_buf();
            }
            here = p.parent();
        }
    }
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(|p| p.parent())
        .expect("ferric-scf manifest dir should be <root>/crates/ferric-scf")
        .to_path_buf()
}

fn reference(system: &str, basis_name: &str) -> Value {
    let path = workspace_root()
        .join(ROW_DIR)
        .join(format!("{system}_{basis_name}.json"));
    let text = std::fs::read_to_string(&path).unwrap_or_else(|e| {
        panic!(
            "missing reference {} ({e}); regenerate with scripts/validation/gen_rohf_hessian.py \
             — a missing reference is a failure, never a skip",
            path.display()
        )
    });
    serde_json::from_str(&text).unwrap_or_else(|e| panic!("{}: bad JSON: {e}", path.display()))
}

fn matrix(v: &Value, ptr: &str) -> Array2<f64> {
    let rows = v
        .pointer(ptr)
        .and_then(Value::as_array)
        .unwrap_or_else(|| panic!("reference field {ptr} missing"));
    let (n, m) = (rows.len(), rows[0].as_array().unwrap().len());
    let mut out = Array2::<f64>::zeros((n, m));
    for (i, row) in rows.iter().enumerate() {
        for (j, x) in row.as_array().unwrap().iter().enumerate() {
            out[(i, j)] = x.as_f64().unwrap();
        }
    }
    out
}

fn load_validation_molecule(system: &str, mult: usize) -> Molecule {
    let xyz = workspace_root().join(MOL_DIR).join(format!("{system}.xyz"));
    Molecule::load_xyz_with_charge(xyz.to_str().unwrap(), 0, mult)
        .unwrap_or_else(|e| panic!("{}: {e:?}", xyz.display()))
}

fn check_state_against_pyscf(system: &str) {
    let r = reference(system, "cc-pvdz");
    let mult = r["multiplicity"].as_u64().unwrap() as usize;
    let mol = load_validation_molecule(system, mult);
    let (prep, bounds) = prep_for(&mol, "cc-pvdz");
    let op = Operator::coulomb();
    let rohf = solve_rohf(
        &ParallelContext::default(),
        &mol,
        &prep,
        op,
        &bounds,
        &scf_config(),
    )
    .unwrap();
    let e_ref = r["energy"].as_f64().unwrap();
    let de = (rohf.energy - e_ref).abs();
    let g = rohf_gradient(&mol, &prep, op, &bounds, &rohf, None).unwrap();
    let dg = max_abs_diff(&g, &matrix(&r, "/gradient"));
    eprintln!("{system}: |E - E_PySCF| = {de:.3e}, max|g - g_PySCF| = {dg:.3e}");
    assert!(de < TOL_ENERGY, "{system}: ROHF energy off by {de:.3e}");
    assert!(dg < TOL_GRADIENT, "{system}: ROHF gradient off by {dg:.3e}");
}

