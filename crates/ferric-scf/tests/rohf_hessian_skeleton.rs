fn check_skeleton_pieces(mol: &Molecule, basis_name: &str) {
    if !has_deriv2() {
        return;
    }
    let fx = fixture(mol, basis_name);
    let p = &fx.parts;
    let tag = format!("{basis_name}/{}atoms", mol.atoms.len());

    let fd_1e = fx.fd_one_electron();
    assert_close(
        &format!("{tag}: V_nn + D·h''"),
        &(&p.nuclear + &p.one_electron),
        &fd_1e,
        TOL_SKELETON_FD,
    );

    let fd_s = fx.fd_overlap();
    assert!(max_abs(&p.overlap) > 1e-2, "vacuous: overlap term is ~0");
    assert_close(
        &format!("{tag}: V_nn - W_ROHF·S''"),
        &(&p.nuclear + &p.overlap),
        &fd_s,
        TOL_SKELETON_FD,
    );

    let fd_2e = fx.fd_two_electron();
    assert!(max_abs(&p.two_electron) > 1e-1, "vacuous: 2e term is ~0");
    assert_close(
        &format!("{tag}: Γ_UHF(D_a, D_b)·ERI''"),
        &p.two_electron,
        &fd_2e,
        TOL_SKELETON_FD,
    );

    // The whole rohf_gradient, its own W and Γ, frozen result: the three
    // pieces above plus V_nn counted once.
    let fd_all = fx.fd_total();
    assert_close(
        &format!("{tag}: whole skeleton vs FD of rohf_gradient"),
        &p.skeleton(),
        &fd_all,
        TOL_SKELETON_FD,
    );
}

