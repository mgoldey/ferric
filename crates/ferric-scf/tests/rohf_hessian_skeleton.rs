//! ROHF Hessian SKELETON (`ferric_scf::hessian::rohf_skeleton_parts`, terms
//! 1-4 of issue #291) against independent constructions. The orbital response
//! (term 5) does not exist yet, so the public Hessian entry points REFUSE ROHF
//! and nothing here is a Hessian: each test compares a skeleton piece to the
//! derivative of the matching piece of `rohf_gradient` at FROZEN densities and
//! frozen energy-weighted density `W`.
//!
//! ```text
//! OPENBLAS_NUM_THREADS=1 cargo test -p ferric-scf --release --test rohf_hessian_skeleton
//! ```
//!
//! # What is compared to what
//!
//! * Per-term FD (the `uhf_hessian_fd.rs::check_skeleton_*` pattern). The
//!   reference is a Richardson-extrapolated central difference
//!   (`(4 D(h/2) - D(h)) / 3`, h = 2e-3 Bohr) of
//!   - `oneelectron_gradient(D_a + D_b, W = 0)`   vs `nuclear + one_electron`
//!   - `oneelectron_gradient(D = 0, W_ROHF)`      vs `nuclear + overlap`
//!   - `twoelectron_gradient_uhf(D, D_a, D_b)`    vs `two_electron`
//!   - the whole `rohf_gradient(result)` with the SAME `ScfResult` reused at
//!     every displaced geometry (its densities and spin Focks are AO matrices,
//!     so they are frozen by construction) vs the sum of all four.
//! * Closed-shell anchor: a singlet ROHF equals the RHF skeleton term by term
//!   (`D_a = D_b = D/2`, `W = D F D / 2 = 2 C eps C^T`), both from a real
//!   `solve_rohf` and from an RHF result relabelled as ROHF.
//! * Translational invariance: every skeleton row sums to zero over the second
//!   atom (the frozen-density functional is shift invariant), and symmetry.
//! * PySCF state anchor: ferric's ROHF energy and `rohf_gradient` equal PySCF's
//!   at the validation geometries, so the reference FD Hessians
//!   (`testdata/reference/validation/rohf_hessian/`, generated by
//!   `scripts/validation/gen_rohf_hessian.py`) describe the same state the
//!   skeleton is built on. Those FD Hessians are the PR-3 target; here ferric's
//!   own FD of `rohf_gradient` is compared to them once (NH2) to size the
//!   floor the full Hessian will be judged against.
//! * Mutation tests: `rohf_skeleton_from_densities` is handed deliberately
//!   wrong densities / `W`; each mutant must miss the matching FD reference by
//!   more than `MUST_MISS_FACTOR` x the bar.
//!
//! # Physics hypothesis vs artifact hypothesis
//!
//! * Right: each piece matches its frozen FD at the Richardson floor; the
//!   singlet anchor agrees at SCF-convergence level; row sums vanish.
//! * `W` wrong (UHF eigenvalue form, Roothaan `C diag(2 eps_c, eps_o) C^T`,
//!   alpha/beta swapped, a term dropped): ONLY the overlap piece changes; the
//!   1e and 2e pieces and the closed-shell anchor are blind to it (at D_a = D_b
//!   the wrong forms coincide with the right one for the Roothaan and UHF
//!   forms). That is why the open-shell overlap FD exists.
//! * Gamma wrong (RHF-form exchange, doubled exchange): ONLY the 2e piece
//!   changes; the singlet anchor is blind to the RHF-form Gamma (it coincides
//!   with the UHF Gamma at D_a = D_b).
//! * Open-shell occupation counted as closed (`D = 2 D_a`): changes the 1e and
//!   2e pieces.
//! * FD reference broken (e.g. a different `W` inside the displaced gradient):
//!   per-piece and total tests disagree with each other, anchors stay clean.
//!
//! # Mutants that are IDENTITIES (blind spots, algebra first)
//!
//! * `D_a F_b D_b -> D_b F_b D_b` in `W`: the difference is
//!   `sym(P_o F_b P_c)`, the closed-open block of `F_b`, which ROHF
//!   stationarity zeroes (`rohf_newton`'s oc gradient block IS `F_b[oc]`). At
//!   convergence this is an identity; the test records its size and does NOT
//!   count it as a caught mutant.
//! * Swapping `D_a <-> D_b` inside Gamma / the 1e density: `Gamma_UHF` and
//!   `D_a + D_b` are symmetric under the swap, so it is an exact identity
//!   (asserted bit-level). Only the swap inside `W` is a real mutant.
//!
//! # TOLERANCES
//!
//! See the constants: each bar sits above the maximum measured on this box
//! (written next to it) and more than `MUST_MISS_FACTOR` below the smallest
//! mutant miss on the same data.

