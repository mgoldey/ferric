fn assert_skeleton_equals_rhf(
    ctx: &str,
    p: &RohfSkeletonParts,
    rhf: &ferric_scf::hessian::RhfHessianParts,
    tol: f64,
) {
    let terms = [
        ("nuclear", &p.nuclear, &rhf.nuclear),
        ("one_electron", &p.one_electron, &rhf.one_electron),
        ("overlap", &p.overlap, &rhf.overlap),
        ("two_electron", &p.two_electron, &rhf.two_electron),
    ];
    for (what, got, want) in terms {
        assert_close(&format!("{ctx} {what}"), got, want, tol);
    }
}

#[test]
fn singlet_rohf_skeleton_equals_rhf_skeleton() {
    if !has_deriv2() {
        return;
    }
    let mol = mol_of(WATER_DISTORTED, 1);
    let (prep, bounds) = prep_for(&mol, "6-31g");
    let ctx = ParallelContext::default();
    let op = Operator::coulomb();
    let cfg = scf_config();
    let rhf = solve_rhf(&ctx, &mol, &prep, op, &bounds, &cfg).unwrap();
    assert!(rhf.converged);
    let r = rhf_hessian_parts(&ctx, &mol, &prep, op, &bounds, &rhf, &cfg).unwrap();

    // (1) a real ROHF solve on the closed-shell molecule.
    let rohf = solve_rohf(&ctx, &mol, &prep, op, &bounds, &cfg).unwrap();
    let p = rohf_skeleton_parts(&mol, &prep, op, &bounds, &rohf, &cfg).unwrap();
    assert_skeleton_equals_rhf("singlet solve_rohf vs RHF", &p, &r, TOL_ANCHOR);

    // (2) the RHF result relabelled as ROHF (D_a = D_b = D/2, F_a = F_b = F).
    let mut relabelled = rhf.clone();
    let half = 0.5 * rhf.density_r();
    relabelled.spin = Spin::RestrictedOpen;
    relabelled.density_alpha = half.clone();
    relabelled.density_beta = Some(half);
    relabelled.rohf_spin_focks = Some((rhf.fock_r().clone(), rhf.fock_r().clone()));
    let p2 = rohf_skeleton_parts(&mol, &prep, op, &bounds, &relabelled, &cfg).unwrap();
    assert_skeleton_equals_rhf("relabelled RHF vs RHF", &p2, &r, TOL_ANCHOR);

    // The anchor is blind to the RHF-form Gamma and to the Roothaan/UHF W
    // (both coincide with the right ones at D_a = D_b): record that, so the
    // open-shell FD tests are known to be the ones that carry those defects.
    let fx_dens = &p2.densities;
    let rhf_gamma = rohf_skeleton_from_densities(
        &mol,
        &prep,
        op,
        &bounds,
        &cfg,
        RohfSkeletonDensities {
            d_alpha: &fx_dens.d_total * 0.5,
            d_beta: &fx_dens.d_total * 0.5,
            ..fx_dens.clone()
        },
    )
    .unwrap();
    eprintln!(
        "closed-shell anchor is blind to the RHF-form Gamma: |ΔΓ-term| = {:.3e}",
        max_abs_diff(&rhf_gamma.two_electron, &p2.two_electron)
    );
    assert!(max_abs_diff(&rhf_gamma.two_electron, &p2.two_electron) < TOL_ANCHOR);
}

