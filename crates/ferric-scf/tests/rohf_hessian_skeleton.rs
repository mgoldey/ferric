fn has_deriv2() -> bool {
    let order = ferric_integrals::engine::libint_max_deriv_order();
    if order < 2 {
        eprintln!("SKIP: libint2 generated with derivative order {order}; no analytic Hessian");
    }
    order >= 2
}

fn mol_of(xyz: &str, mult: usize) -> Molecule {
    Molecule::parse_xyz(xyz, 0, mult).unwrap()
}

/// Exact J/K, tight convergence.
fn scf_config() -> RhfConfig {
    RhfConfig {
        max_iter: 500,
        energy_conv: 1e-12,
        density_conv: 1e-10,
        df_j_aux: Some(String::new()),
        df_k_aux: Some(String::new()),
        ..Default::default()
    }
}

fn prep_for(m: &Molecule, basis_name: &str) -> (PreparedBasis, SchwarzBounds) {
    let bs = basis::bundled(basis_name).unwrap();
    let prep = PreparedBasis::new(m, &bs).unwrap();
    let bounds = SchwarzBounds::compute(Operator::coulomb(), &prep).unwrap();
    (prep, bounds)
}

struct Fixture {
    mol: Molecule,
    basis_name: String,
    prep: PreparedBasis,
    bounds: SchwarzBounds,
    rohf: ScfResult,
    parts: RohfSkeletonParts,
}

fn fixture(mol: &Molecule, basis_name: &str) -> Fixture {
    let (prep, bounds) = prep_for(mol, basis_name);
    let rohf = solve_rohf(
        &ParallelContext::default(),
        mol,
        &prep,
        Operator::coulomb(),
        &bounds,
        &scf_config(),
    )
    .unwrap();
    assert!(rohf.converged, "{basis_name}: reference ROHF not converged");
    let parts = rohf_skeleton_parts(
        mol,
        &prep,
        Operator::coulomb(),
        &bounds,
        &rohf,
        &scf_config(),
    )
    .unwrap();
    Fixture {
        mol: mol.clone(),
        basis_name: basis_name.to_string(),
        prep,
        bounds,
        rohf,
        parts,
    }
}

impl Fixture {
    fn d_total(&self) -> &Array2<f64> {
        &self.parts.densities.d_total
    }

    fn w(&self) -> &Array2<f64> {
        &self.parts.densities.w
    }

    /// Skeleton with one of the inputs replaced.
    fn mutated(&self, f: impl FnOnce(&mut RohfSkeletonDensities)) -> RohfSkeletonParts {
        let mut dens = self.parts.densities.clone();
        f(&mut dens);
        rohf_skeleton_from_densities(
            &self.mol,
            &self.prep,
            Operator::coulomb(),
            &self.bounds,
            &scf_config(),
            dens,
        )
        .unwrap()
    }

    fn fd(
        &self,
        grad: impl FnMut(&Molecule, &PreparedBasis, &SchwarzBounds) -> Array2<f64>,
    ) -> Array2<f64> {
        fd_richardson(&self.mol, &self.basis_name, H_SKELETON, grad)
    }

    /// FD of the one-electron+nuclear gradient piece at frozen D (W = 0).
    fn fd_one_electron(&self) -> Array2<f64> {
        let d = self.d_total().clone();
        let zero = Array2::<f64>::zeros(d.dim());
        self.fd(|m, prep, _| oneelectron_gradient(m, prep, &d, &zero, None).unwrap())
    }

    /// FD of the overlap gradient piece at frozen W (D = 0).
    fn fd_overlap(&self) -> Array2<f64> {
        let w = self.w().clone();
        let zero = Array2::<f64>::zeros(w.dim());
        self.fd(|m, prep, _| oneelectron_gradient(m, prep, &zero, &w, None).unwrap())
    }

    fn fd_two_electron(&self) -> Array2<f64> {
        let (d, da, db) = (
            self.parts.densities.d_total.clone(),
            self.parts.densities.d_alpha.clone(),
            self.parts.densities.d_beta.clone(),
        );
        self.fd(|_, prep, bounds| {
            twoelectron_gradient_uhf(prep, Operator::coulomb(), bounds, &d, &da, &db).unwrap()
        })
    }

    /// FD of the whole `rohf_gradient` with this fixture's `ScfResult` frozen.
    fn fd_total(&self) -> Array2<f64> {
        let res = self.rohf.clone();
        self.fd(|m, prep, bounds| {
            rohf_gradient(m, prep, Operator::coulomb(), bounds, &res, None).unwrap()
        })
    }
}

fn displaced(mol: &Molecule, atom: usize, coord: usize, h: f64) -> Molecule {
    let mut m = mol.clone();
    match coord {
        0 => m.atoms[atom].x += h,
        1 => m.atoms[atom].y += h,
        _ => m.atoms[atom].zpos += h,
    }
    m
}

/// Central-difference Hessian: column b = (g(x_b + h) - g(x_b - h)) / 2h.
fn fd_hessian(
    mol: &Molecule,
    basis_name: &str,
    h: f64,
    grad: &mut impl FnMut(&Molecule, &PreparedBasis, &SchwarzBounds) -> Array2<f64>,
) -> Array2<f64> {
    let n3 = 3 * mol.atoms.len();
    let mut out = Array2::<f64>::zeros((n3, n3));
    for b in 0..n3 {
        let mut g = |sign: f64| {
            let m = displaced(mol, b / 3, b % 3, sign * h);
            let (prep, bounds) = prep_for(&m, basis_name);
            grad(&m, &prep, &bounds)
        };
        let (gp, gm) = (g(1.0), g(-1.0));
        for a in 0..n3 {
            out[(a, b)] = (gp[(a / 3, a % 3)] - gm[(a / 3, a % 3)]) / (2.0 * h);
        }
    }
    out
}

/// `(4 D(h/2) - D(h)) / 3`: removes the O(h^2) term of the central difference.
fn fd_richardson(
    mol: &Molecule,
    basis_name: &str,
    h: f64,
    mut grad: impl FnMut(&Molecule, &PreparedBasis, &SchwarzBounds) -> Array2<f64>,
) -> Array2<f64> {
    let coarse = fd_hessian(mol, basis_name, h, &mut grad);
    let fine = fd_hessian(mol, basis_name, 0.5 * h, &mut grad);
    (4.0 * fine - coarse) / 3.0
}

fn max_abs_diff(a: &Array2<f64>, b: &Array2<f64>) -> f64 {
    assert_eq!(a.dim(), b.dim());
    a.iter()
        .zip(b.iter())
        .fold(0.0f64, |m, (x, y)| m.max((x - y).abs()))
}

fn max_abs(a: &Array2<f64>) -> f64 {
    a.iter().fold(0.0f64, |m, x| m.max(x.abs()))
}

fn assert_close(ctx: &str, got: &Array2<f64>, want: &Array2<f64>, tol: f64) {
    let d = max_abs_diff(got, want);
    eprintln!(
        "{ctx}: max|got - want| = {d:.3e} (max|want| {:.3e}, tol {tol:.0e})",
        max_abs(want)
    );
    assert!(d < tol, "{ctx}: max|got - want| = {d:.3e} >= {tol:.0e}");
}

/// A mutant must miss `want` by more than `MUST_MISS_FACTOR` x `bar`.
fn assert_miss(ctx: &str, mutant: &Array2<f64>, want: &Array2<f64>, bar: f64) {
    let d = max_abs_diff(mutant, want);
    eprintln!(
        "MUTANT {ctx}: misses by {d:.3e} = {:.1}x the bar {bar:.0e}",
        d / bar
    );
    assert!(
        d > MUST_MISS_FACTOR * bar,
        "MUTANT {ctx} missed by only {d:.3e} (<= {MUST_MISS_FACTOR} x {bar:.0e}): the test \
         cannot see this defect"
    );
}

