fn check_density_mutants(mol: &Molecule, basis_name: &str) {
    if !has_deriv2() {
        return;
    }
    let fx = fixture(mol, basis_name);
    let fd_2e = fx.fd_two_electron();
    let fd_1e = fx.fd_one_electron();
    let p0 = &fx.parts;
    let tag = format!("{basis_name}/{}atoms", mol.atoms.len());
    let (da, db, d) = (
        p0.densities.d_alpha.clone(),
        p0.densities.d_beta.clone(),
        p0.densities.d_total.clone(),
    );

    // Control.
    assert_close(
        &format!("{tag} Gamma control (correct)"),
        &p0.two_electron,
        &fd_2e,
        TOL_SKELETON_FD,
    );

    // Wrong exchange: the RHF-form Gamma (D_a = D_b = D/2).
    let p = fx.mutated(|x| {
        x.d_alpha = &d * 0.5;
        x.d_beta = &d * 0.5;
    });
    assert_miss(
        &format!("{tag} RHF-form exchange in Gamma"),
        &p.two_electron,
        &fd_2e,
        TOL_SKELETON_FD,
    );

    // Dropped 1/2 on the exchange (exchange counted twice): scale D_a, D_b by
    // sqrt(2) inside Gamma's exchange, the Coulomb density untouched.
    let p = fx.mutated(|x| {
        x.d_alpha = &da * std::f64::consts::SQRT_2;
        x.d_beta = &db * std::f64::consts::SQRT_2;
    });
    assert_miss(
        &format!("{tag} exchange without its 1/2"),
        &p.two_electron,
        &fd_2e,
        TOL_SKELETON_FD,
    );

    // Open-shell occupation counted as closed: D = 2 D_a everywhere it is
    // the total density (1e term and the Coulomb half of Gamma).
    let p = fx.mutated(|x| x.d_total = &da * 2.0);
    assert_miss(
        &format!("{tag} open shell counted doubly in D (1e)"),
        &(&p.nuclear + &p.one_electron),
        &fd_1e,
        TOL_SKELETON_FD,
    );
    assert_miss(
        &format!("{tag} open shell counted doubly in D (Coulomb of Gamma)"),
        &p.two_electron,
        &fd_2e,
        TOL_SKELETON_FD,
    );

    // IDENTITY: swapping D_a <-> D_b (Gamma_UHF and D_a + D_b are symmetric).
    let p = fx.mutated(|x| {
        x.d_alpha = db.clone();
        x.d_beta = da.clone();
    });
    let delta = max_abs_diff(&p.two_electron, &p0.two_electron);
    eprintln!("{tag} IDENTITY mutant D_a <-> D_b in Gamma: |Δ2e| = {delta:.3e}");
    assert!(
        delta < 1e-12,
        "alpha/beta swap in Gamma must be an identity"
    );
}

