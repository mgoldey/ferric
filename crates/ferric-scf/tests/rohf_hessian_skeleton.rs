/// `C diag(w_i eps_i) C^T` over the first `weights.len()` MOs.
fn w_from_eps(c: &Array2<f64>, eps: &[f64], weights: &[f64]) -> Array2<f64> {
    let n = weights.len();
    let c_occ = c.slice(ndarray::s![.., ..n]);
    let scale = Array1::from_iter((0..n).map(|i| weights[i] * eps[i]));
    let cw = &c_occ * &scale;
    cw.dot(&c_occ.t())
}

fn sym(m: &Array2<f64>) -> Array2<f64> {
    0.5 * (m + &m.t())
}

/// `(n_closed, n_open)` of a ROHF fixture.
fn shells(fx: &Fixture) -> (usize, usize) {
    let nelec = fx.mol.nelec() as usize;
    let n_open = fx.mol.multiplicity - 1;
    ((nelec - n_open) / 2, n_open)
}

fn check_w_mutants(mol: &Molecule, basis_name: &str) {
    if !has_deriv2() {
        return;
    }
    let fx = fixture(mol, basis_name);
    let fd_s = fx.fd_overlap();
    let nuc = &fx.parts.nuclear;
    let (nc, no) = shells(&fx);
    let c = &fx.rohf.mos_alpha;
    let eps = &fx.rohf.eps_alpha;
    let (f_a, f_b) = fx.rohf.rohf_spin_focks.clone().unwrap();
    let (da, db) = (
        fx.parts.densities.d_alpha.clone(),
        fx.parts.densities.d_beta.clone(),
    );
    let tag = format!("{basis_name}/{}atoms", mol.atoms.len());

    // Reference: the correct skeleton passes.
    assert_close(
        &format!("{tag} W control (correct)"),
        &(nuc + &fx.parts.overlap),
        &fd_s,
        TOL_SKELETON_FD,
    );

    let mut weights_uhf = vec![2.0; nc];
    weights_uhf.extend(vec![1.0; no]);
    // What `uhf_hessian_parts` would do with a ROHF result: the library's UHF
    // eigenvalue builder. A ROHF result carries no beta orbitals, so only the
    // alpha half is built (the real hazard named in the #291 sizing report).
    let w_uhf_library = build_energy_weighted_density_uhf(&fx.rohf, nc + no, nc);
    // The UHF eigenvalue form with the beta half rebuilt from the SAME orbital
    // set is algebraically C diag(2 eps_c, eps_o) C^T, the Roothaan form below
    // (one mutant, not two).
    // Roothaan form C diag(2 eps_c, eps_o) C^T.
    let w_roothaan = w_from_eps(c, eps, &weights_uhf);
    // alpha <-> beta swapped inside W.
    let w_swapped = sym(&(db.dot(&f_b).dot(&db) + db.dot(&f_a).dot(&da)));
    // second term dropped.
    let w_drop = sym(&da.dot(&f_a).dot(&da));

    let mutants = [
        (
            "W = build_energy_weighted_density_uhf (alpha half only)",
            w_uhf_library,
        ),
        (
            "W = Roothaan C diag(2eps_c, eps_o) C^T (= UHF form, shared orbitals)",
            w_roothaan,
        ),
        ("W with alpha/beta swapped", w_swapped),
        ("W without D_a F_b D_b", w_drop),
    ];
    for (name, w) in mutants {
        let p = fx.mutated(|d| d.w = w);
        assert_miss(
            &format!("{tag} {name}"),
            &(nuc + &p.overlap),
            &fd_s,
            TOL_SKELETON_FD,
        );
    }

    // IDENTITY at convergence: D_a F_b D_b -> D_b F_b D_b changes W by
    // sym(P_o F_b P_c), the closed-open block of F_b, which ROHF stationarity
    // zeroes. NOT counted as a caught mutant.
    let w_ident = sym(&(da.dot(&f_a).dot(&da) + db.dot(&f_b).dot(&db)));
    let p = fx.mutated(|d| d.w = w_ident);
    let miss = max_abs_diff(&(nuc + &p.overlap), &fd_s);
    eprintln!(
        "{tag} IDENTITY mutant D_a F_b D_b -> D_b F_b D_b: |Δoverlap| vs FD = {miss:.3e} \
         (blind by construction; the oc block of F_b is {:.3e})",
        max_abs(&(da.dot(&f_b).dot(&db) - db.dot(&f_b).dot(&db)))
    );
    assert!(
        miss < TOL_SKELETON_FD,
        "the identity mutant must be invisible at convergence, got {miss:.3e}"
    );
}

