#[test]
fn public_hessian_entry_points_refuse_rohf_and_name_the_gap() {
    if !has_deriv2() {
        return;
    }
    let fx = fixture(&mol_of(CH2_DISTORTED, 3), "sto-3g");
    let ctx = ParallelContext::default();
    let op = Operator::coulomb();
    let cfg = scf_config();
    for (name, err) in [
        (
            "rhf_hessian",
            rhf_hessian(&ctx, &fx.mol, &fx.prep, op, &fx.bounds, &fx.rohf, &cfg).unwrap_err(),
        ),
        (
            "uhf_hessian",
            uhf_hessian(&ctx, &fx.mol, &fx.prep, op, &fx.bounds, &fx.rohf, &cfg).unwrap_err(),
        ),
    ] {
        let msg = err.to_string();
        eprintln!("{name}: {msg}");
        assert!(msg.contains("ROHF"), "{name}: {msg}");
        assert!(
            msg.contains("orbital response"),
            "{name}: the refusal must name the missing piece: {msg}"
        );
    }
    // And the skeleton builder refuses non-ROHF results.
    let (prep, bounds) = prep_for(&mol_of(WATER_DISTORTED, 1), "sto-3g");
    let water = mol_of(WATER_DISTORTED, 1);
    let rhf = solve_rhf(&ctx, &water, &prep, op, &bounds, &cfg).unwrap();
    assert!(rohf_skeleton_parts(&water, &prep, op, &bounds, &rhf, &cfg).is_err());
    let ks = RhfConfig {
        xc: Some("PBE".into()),
        ..scf_config()
    };
    assert!(rohf_skeleton_parts(&fx.mol, &fx.prep, op, &fx.bounds, &fx.rohf, &ks).is_err());
}

