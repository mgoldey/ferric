/// ferric's central FD of `rohf_gradient` (SCF re-converged at each displaced
/// geometry) vs PySCF's FD of its analytic ROHF gradient: the floor the full
/// ROHF Hessian (PR-3) will be judged against, and a check that the stored
/// reference describes ferric's state. 6N re-converged cc-pVDZ ROHF solves,
/// 4.5 s measured; needs no second-derivative integrals. Measured max|d|
/// 5.2e-7 (PySCF's own h-vs-2h truncation gap on NH2 is 6.7e-7).
#[test]
fn ferric_fd_of_rohf_gradient_matches_pyscf_fd_hessian_nh2() {
    let r = reference("nh2", "cc-pvdz");
    let mol = load_validation_molecule("nh2", 2);
    let op = Operator::coulomb();
    let ctx = ParallelContext::default();
    let mut grad = |m: &Molecule, prep: &PreparedBasis, bounds: &SchwarzBounds| {
        let res = solve_rohf(&ctx, m, prep, op, bounds, &scf_config()).unwrap();
        rohf_gradient(m, prep, op, bounds, &res, None).unwrap()
    };
    let h = fd_hessian(&mol, "cc-pvdz", 1e-3, &mut grad);
    let want = matrix(&r, "/hessian_fd");
    let d = max_abs_diff(&(0.5 * (&h + &h.t())), &want);
    eprintln!("ferric FD vs PySCF FD Hessian (NH2/cc-pVDZ): max|d| = {d:.3e}");
    assert!(d < 3e-6, "ferric FD Hessian vs PySCF FD Hessian: {d:.3e}");
}
