///
/// | Schwarz-table precision | Q == 0 pairs | LinK(thresh=0) max\|dK\| |
/// |-------------------------|--------------|-------------------------|
/// | 1e-14 (production)      | 1049 / 5253  | 1.96e-3                 |
/// | 1e-20                   |  529 / 5253  | 5.44e-4                 |
/// | 1e-26                   |  226 / 5253  | 2.11e-4                 |
/// | 1e-32                   |  133 / 5253  | 9.03e-5                 |
///
/// Note this is invisible on the molecules the pre-existing `link_k.rs` tests
/// use: water and CH4 have NO underflowed pairs, so LinK is exact there and
/// those tests pass while proving nothing about this.
///
/// Assertion shape matches the energy defect below: an upper bound that
/// catches regression, and a lower bound that FAILS ONCE FIXED so the claim
/// cannot go stale.
#[test]
fn link_k_cannot_reach_the_dense_answer_alkane_8() {
    let mol = load_mol("alkane_8");
    let bs = basis::bundled("cc-pvdz").expect("basis");
    let prep = PreparedBasis::new(&mol, &bs).expect("PreparedBasis");
    let nsh = prep.nshells();
    let full_triangle = nsh * (nsh + 1) / 2;
    let d = converged_density(&mol, &bs, &prep);

    // The trivial limit: screening disabled on BOTH sides.
    let k_dense = dense_k(&prep, &d, 0.0);
    let k_link = link_k(BoundKind::Schwarz, &mol, &bs, &prep, &d, 0.0);
    let err = max_abs_diff(&k_link, &k_dense);

    let bound = make_bound(BoundKind::Schwarz, &mol, &bs, &prep, Operator::coulomb());
    let retained = SignificantPairs::build(bound.as_dyn(), nsh, 0.0).total_pairs() / 2;

    eprintln!(
        "alkane_8/cc-pVDZ LinK trivial limit (thresh=0): max|K_link - K_dense| = {err:.4e}, \
         significant pairs {retained} / {full_triangle}"
    );

    assert!(
        err < 1e-2,
        "alkane_8: LinK-vs-dense error at thresh=0 is {err:.4e}, worse than the ~1.96e-3 recorded \
         when this test was written — the exactness defect has regressed"
    );
    assert!(
        err > 1e-4,
        "alkane_8: LinK now reproduces the dense K at thresh=0 to {err:.4e}. If the Schwarz \
         Q-underflow defect has been FIXED, this test has done its job: delete it, restore a real \
         `link_k_matches_dense_in_the_trivial_limit` assertion (err < 1e-10) in its place, and \
         tighten LINK_VS_DENSE_SLACK/the energy bars accordingly."
    );
    assert!(
        retained < full_triangle,
        "alkane_8: SignificantPairs now retains all {full_triangle} pairs at thresh=0 — the \
         underflow defect appears fixed; see the message above for what to do."
    );
}

/// KNOWN DEFECT, pinned: screening at the default `integral_thresh` shifts the
/// Coulomb energy by an amount that GROWS with system size.
///
/// This is the finding that came out of building the anchors in this file, and
/// it is recorded as an executable fact rather than a comment so that a fix
/// (or a regression) is detected rather than argued about.
///
/// What is measured, on ONE fixed density per molecule (PySCF's converged
/// density, read from the reference file), contracted twice — once with the
/// production screen and once with screening disabled:
///
///   alkane_4:  |E(1e-14) - E(0)| ~ 5.0e-9   (negligible)
///   alkane_8:  |E(1e-14) - E(0)| ~ 1.8e-4   (35000x larger)
///
/// (alkane_4 contracts PySCF's density, alkane_8 ferric's own — see the code.
/// The choice is immaterial: each shift is a ferric-vs-ferric difference at
/// two thresholds on ONE fixed density. On PySCF's density alkane_8 gives
/// 1.14e-4 rather than 1.79e-4; same phenomenon, same order.)
///
/// Using one fixed density for both builds removes the SCF entirely from the
/// comparison: any difference is the screen and nothing else.
///
/// Mechanism (see `directjk_matches_pyscf_alkane_8`): Q entries that underflow
/// to exactly 0.0 at libint2's hardcoded 1e-14 engine precision cause every
/// quartet on that shell pair to be screened at any positive threshold.
///
/// The assertion is deliberately two-sided. The upper bound catches the defect
/// getting WORSE. The lower bound FAILS ONCE THE DEFECT IS FIXED — that is
/// intentional, so nobody fixes the screen and leaves this test quietly
/// asserting a stale claim; the fix should delete this test (or invert it) and
/// tighten `directjk_matches_pyscf_alkane_8`'s energy bar to 1e-8.
#[test]
fn known_defect_screening_shifts_coulomb_energy_with_size() {
    let mut shifts = Vec::new();
    for tag in ["alkane_4", "alkane_8"] {
        let rec = DirectJkRef::load(tag);
        let mol = load_mol(tag);
        let bs = basis::bundled("cc-pvdz").expect("basis");
        let prep = PreparedBasis::new(&mol, &bs).expect("PreparedBasis");
        let nbf = prep.nbasis();
        let op = Operator::coulomb();
        let bounds = SchwarzBounds::compute(op, &prep).expect("Schwarz bounds");

        // Use PySCF's density when the reference carries it (so the two
        // molecules' numbers are directly comparable to the cross-code test
        // above), and ferric's own converged density otherwise. Either works:
        // the comparison here is ferric-vs-ferric at two thresholds on ONE
        // fixed density, so the density's provenance is irrelevant as long as
        // it is the same on both sides of the subtraction.
        let d = if rec.has_matrices() {
            let d_pyscf = rec.square(&rec.density);
            let mut d = Array2::<f64>::zeros((nbf, nbf));
            for i in 0..nbf {
                for j in 0..nbf {
                    d[(i, j)] = d_pyscf[(rec.ao_permutation[i], rec.ao_permutation[j])];
                }
            }
            d
        } else {
            converged_density(&mol, &bs, &prep)
        };

        let h = ferric_integrals::oneelectron::hcore(&prep);
        let vnn = mol.nuclear_repulsion();
        let energy_at = |thresh: f64| -> f64 {
            let mut j = Array2::zeros((nbf, nbf));
            let mut k = Array2::zeros((nbf, nbf));
            build_jk(
                &ParallelContext::default(),
                &prep,
                &bounds,
                thresh,
                &d,
                &mut j,
                &mut k,
            )
            .expect("build_jk");
            let f = &h + &j - &(0.5 * &k);
            0.5 * (&d * &(&h + &f)).sum() + vnn
        };

        let e_screened = energy_at(PRODUCTION_INTEGRAL_THRESH);
        let e_exact = energy_at(0.0);
        let shift = (e_screened - e_exact).abs();
        eprintln!(
            "{tag}: E(thresh=1e-14) = {e_screened:.12}, E(thresh=0) = {e_exact:.12}, \
             |shift| = {shift:.3e} Ha"
        );
        shifts.push((tag, shift));
    }

    let (_, s4) = shifts[0];
    let (_, s8) = shifts[1];

    assert!(
        s4 < 1e-7,
        "alkane_4 screening shift {s4:.3e} Ha is larger than the ~5e-9 recorded when this test \
         was written — the screening defect has gotten worse on SMALL systems too"
    );
    assert!(
        s8 < 1e-3,
        "alkane_8 screening shift {s8:.3e} Ha exceeds the ~1.8e-4 recorded when this test was \
         written — the screening defect has gotten worse"
    );
    assert!(
        s8 > 1e-5,
        "alkane_8 screening shift is only {s8:.3e} Ha, far below the 1.8e-4 this test was written \
         to pin. If the Q-underflow screening defect has been FIXED, that is good news and this \
         test has done its job: delete it and tighten the energy bar in \
         directjk_matches_pyscf_alkane_8 from 1e-3 to 1e-8."
    );
    assert!(
        s8 > s4 * 100.0,
        "the screening shift is no longer strongly size-divergent (alkane_4 {s4:.3e} vs alkane_8 \
         {s8:.3e}); re-derive the mechanism before trusting either bar"
    );
}

/// The QQR arm of [`BoundKind`] must stay constructible and usable, so the
/// follow-up PR that turns on QQR screening extends the case lists above
/// rather than discovering that the generic plumbing rotted.
///
/// Deliberately tiny (water/STO-3G): this checks WIRING, not physics — the
/// physics assertions for QQR are the sweep above, once it is enabled.
#[test]
fn qqr_bound_arm_is_wired() {
    let mol = Molecule::parse_xyz(
        "3\nwater\nO 0.000000 0.000000 0.117790\nH 0.000000 0.755453 -0.471161\nH 0.000000 -0.755453 -0.471161\n",
        0,
        1,
    )
    .unwrap();
    let bs = basis::bundled("sto-3g").expect("basis");
    let prep = PreparedBasis::new(&mol, &bs).expect("PreparedBasis");
    let nsh = prep.nshells();
    let op = Operator::coulomb();

    for kind in [BoundKind::Schwarz, BoundKind::Qqr] {
        let bound = make_bound(kind, &mol, &bs, &prep, op);
        // Negative threshold = the vacuous screen; see the longer note in
        // `significant_pairs_actually_screens_alkane_8` for why 0.0 is not it.
        let sp = SignificantPairs::build(bound.as_dyn(), nsh, -1.0);
        assert_eq!(
            sp.total_pairs(),
            nsh * nsh,
            "{}: a negative threshold must retain every ordered shell pair",
            kind.label()
        );
    }
}
