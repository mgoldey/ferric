const WIDTHS: [(&str, f64); 3] = [("0p5", 0.5), ("1", 1.0), ("2", 2.0)];

fn check_smeared(tag: &str, w: f64) {
    let stem = format!("h2o_q10_smeared_w{tag}_cc-pvdz");
    let r = reference(&stem);
    let ctx = stem.clone();
    // The file must be the width we think it is.
    for v in r["widths_bohr"].as_array().unwrap() {
        assert_eq!(v.as_f64().unwrap(), w, "{ctx}: reference width");
    }
    check_case(&stem, Some(w), None, &HF);
    let e_ref = num(&r, "/energy");

    // Point-charge limit of the same sites must MISS (smearing is live).
    let sys_p = build_system(&r, 1.0, None);
    let qm = qm_part(&r, &sys_p, &ctx);
    let point = scf(&qm, Some(&sys_p), None, &format!("{ctx}/point"));
    check_close(
        &ctx,
        "E point limit",
        point.energy,
        num(&r, "/control_point_limit/energy"),
        TOL_E_HF,
    );
    check_misses(
        &ctx,
        "point charges vs smeared ref",
        point.energy,
        e_ref,
        TOL_E_HF,
    );

    // Width swap: every OTHER width must MISS this reference (and match its own).
    for (other_tag, other_w) in WIDTHS {
        if other_w == w {
            continue;
        }
        let sys_o = build_system(&r, 1.0, Some(other_w));
        let e_o = scf(&qm, Some(&sys_o), None, &format!("{ctx}/w{other_tag}")).energy;
        check_close(
            &ctx,
            &format!("E width {other_w}"),
            e_o,
            num(&r, &format!("/control_widths/{other_w}/energy")),
            TOL_E_HF,
        );
        check_misses(
            &ctx,
            &format!("width {other_w} vs width {w} ref"),
            e_o,
            e_ref,
            TOL_E_HF,
        );
    }
    // Unit trap: a width given in Angstrom but read as Bohr (x 1.8897) is a
    // different Gaussian and must MISS.
    let ang2bohr = 1.0 / 0.529_177_210_92;
    let sys_t = build_system(&r, 1.0, Some(w * ang2bohr));
    let e_t = scf(&qm, Some(&sys_t), None, &format!("{ctx}/unit-trap")).energy;
    check_misses(&ctx, "width x 1/0.529 (unit trap)", e_t, e_ref, TOL_E_HF);
}

