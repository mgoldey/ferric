/// The full QM/MM structure as a user builds it: QM atoms first (with a
/// dummy MM charge that must be dropped because they are QM), then one
/// `QmmmAtom` per MM site. `q_scale` multiplies every MM charge; `width`
/// `Some(w)` makes every site a Gaussian of width `w` Bohr.
fn build_system(r: &Value, q_scale: f64, width: Option<f64>) -> QmmmSystem {
    let mut atoms: Vec<QmmmAtom> = r["atoms"]
        .as_array()
        .unwrap()
        .iter()
        .map(|a| {
            let sym = a["symbol"].as_str().unwrap();
            let z = elements::symbol_to_z(sym).unwrap();
            let [x, y, zz] = xyz3(&a["xyz_bohr"]);
            QmmmAtom::new(sym, z, x, y, zz, 99.0)
        })
        .collect();
    let nqm = atoms.len();
    for c in r["mm_charges"].as_array().unwrap() {
        let q = c["q"].as_f64().unwrap() * q_scale;
        let [x, y, z] = xyz3(&c["xyz_bohr"]);
        atoms.push(match width {
            None => QmmmAtom::new("X", 0, x, y, z, q),
            Some(w) => QmmmAtom::new_smeared("X", 0, x, y, z, q, w),
        });
    }
    let charge = r["charge"].as_i64().unwrap() as i32;
    let mult = r["multiplicity"].as_u64().unwrap() as usize;
    QmmmSystem::new(
        &atoms,
        QmSelection::Indices((0..nqm).collect()),
        charge,
        mult,
    )
    .unwrap()
}

struct Qm {
    mol: Molecule,
    bs: BasisSet,
    prep: PreparedBasis,
    bounds: SchwarzBounds,
}

/// QM molecule + basis, with the geometry and AO count asserted against the
/// reference before any SCF runs.
fn qm_part(r: &Value, sys: &QmmmSystem, ctx: &str) -> Qm {
    let mol = sys.to_qm_molecule();
    assert_eq!(
        mol.atoms.len(),
        r["atoms"].as_array().unwrap().len(),
        "{ctx}: QM atom count"
    );
    let enuc = mol.nuclear_repulsion();
    let enuc_ref = num(r, "/nuclear_repulsion");
    assert!(
        (enuc - enuc_ref).abs() < TOL_ENUC,
        "{ctx}: nuclear repulsion {enuc:.12} vs reference {enuc_ref:.12} — geometry/unit mismatch"
    );
    let basis_name = r["basis"].as_str().unwrap();
    let bs = basis::bundled(basis_name).unwrap();
    let prep = PreparedBasis::new(&mol, &bs).unwrap();
    let nao = ferric_integrals::oneelectron::overlap(&prep).nrows();
    assert_eq!(nao as u64, r["nao"].as_u64().unwrap(), "{ctx}: AO count");
    let bounds = SchwarzBounds::compute(Operator::coulomb(), &prep).unwrap();
    Qm {
        mol,
        bs,
        prep,
        bounds,
    }
}

/// ferric's spelling of the functional.
fn ferric_xc(xc: &str) -> &'static str {
    match xc {
        "b3lyp" => "B3LYP",
        "pbe" => "PBE",
        other => panic!("unknown functional {other}"),
    }
}

fn config(
    xc: Option<&str>,
    ext: Option<ferric_core::external_potential::ExternalPotential>,
) -> RhfConfig {
    match xc {
        None => RhfConfig {
            external_potential: ext,
            energy_conv: 1e-11,
            density_conv: 1e-10,
            max_iter: 300,
            ..Default::default()
        },
        Some(xc) => RhfConfig {
            xc: Some(ferric_xc(xc).into()),
            // Exact four-centre J and K, matching PySCF RKS without density_fit.
            df_j_aux: Some(String::new()),
            df_k_aux: Some(String::new()),
            external_potential: ext,
            energy_conv: 1e-10,
            density_conv: 1e-8,
            max_iter: 300,
            ..Default::default()
        },
    }
}

fn scf(qm: &Qm, sys: Option<&QmmmSystem>, xc: Option<&str>, ctx: &str) -> ScfResult {
    let ext = sys.map(|s| {
        s.to_external_potential()
            .unwrap_or_else(|| panic!("{ctx}: MM region produced no potential"))
    });
    let cfg = config(xc, ext);
    let res = solve_rhf(
        &ParallelContext::default(),
        &qm.mol,
        &qm.prep,
        Operator::coulomb(),
        &qm.bounds,
        &cfg,
    )
    .unwrap_or_else(|e| panic!("{ctx}: solve_rhf failed: {e:?}"));
    assert!(res.converged, "{ctx}: SCF not converged");
    res
}

fn gradient(qm: &Qm, res: &ScfResult, sys: Option<&QmmmSystem>, xc: Option<&str>) -> Array2<f64> {
    let ext = sys.and_then(|s| s.to_external_potential());
    match xc {
        None => rhf_gradient(
            &qm.mol,
            &qm.prep,
            Operator::coulomb(),
            &qm.bounds,
            res,
            ext.as_ref(),
        )
        .unwrap(),
        Some(xc) => ks_gradient_closed(
            &qm.mol,
            &qm.prep,
            &qm.bs,
            Operator::coulomb(),
            &qm.bounds,
            ferric_xc(xc),
            res,
            ext.as_ref(),
        )
        .unwrap(),
    }
}

