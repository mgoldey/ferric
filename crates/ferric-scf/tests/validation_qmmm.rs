//! VALIDATION tier — VALIDATION.md rows "QM/MM", "Smeared charges" and
//! "KS QM/MM". The row "External potential in MP2 gradients" is in
//! `crates/ferric-mp2/tests/validation_qmmm_mp2_gradient.rs`.
//!
//! Runs only in the weekly `validation` CI job (and on demand):
//!
//! ```text
//! cargo nextest run -p ferric-scf --test validation_qmmm \
//!     --run-ignored only -E 'binary(/^validation_/)'
//! ```
//!
//! # What is compared
//!
//! ferric's electrostatic embedding (`ferric_scf::qmmm::QmmmSystem` →
//! `ExternalPotential` folded into hcore, `rhf_gradient`/`ks_gradient_closed`
//! for the QM nuclei, `mm_forces` for the MM sites) against PySCF 2.13
//! `pyscf.qmmm.mm_charge`, an independent implementation of the same model.
//! References: `testdata/reference/validation/qmmm/*.json`, generated by
//! `scripts/validation/gen_qmmm.py` from ferric's own bundled basis JSON and
//! ferric's geometry in Bohr (`scripts/validation/common.py`).
//!
//! | test | QM / basis | MM | method |
//! |---|---|---|---|
//! | `point_*` | H2O / cc-pVDZ, aug-cc-pVDZ | 10 charges: two H-bonded TIP3P waters, ±1 ions, ±0.3 | RHF |
//! | `point_ch3oh_tip3p501` | CH3OH / 6-31G | 501 TIP3P charges, seeded random shell (`testdata/molecules/validation/ch3oh_tip3p_shell.json`) | RHF |
//! | `smeared_*` | H2O / cc-pVDZ | the 10 sites, Gaussian width 0.5 / 1.0 / 2.0 Bohr | RHF |
//! | `ks_*` | CH3OH / def2-SVP | the 20 shell sites nearest the QM atoms | RKS B3LYP, PBE |
//!
//! Each case asserts the embedded total energy, the gas-phase energy, the
//! embedding SHIFT (their difference), the QM nuclear gradient and the force
//! on every MM site. No charge set has a symmetry, so every gradient
//! component is live.
//!
//! Like-for-like settings: exact four-centre J/K on both sides for HF AND for
//! KS (ferric `df_j_aux = df_k_aux = Some("")`; RI-J is ferric's KS default,
//! so leaving them unset would compare against the RI fitting error). KS grid:
//! (75,110) unpruned, Becke partition with Becke-1988 radii on both sides.
//! ferric's KS gradient includes the grid response, so it is compared against
//! PySCF `grid_response = True`; PySCF's `grid_response = False` gradient is
//! also recorded in the JSON and differs from it by up to 1.8e-3 Ha/Bohr on
//! these systems (the grid-weight derivative at (75,110)).
//!
//! # Smeared-charge unit convention (read from both sources)
//!
//! ferric `QmmmAtom::width` / `SmearedCharge::width` is in Bohr with
//! ζ = 1/width². PySCF `mm_charge(radii=)` reads the radius in the SAME unit
//! as the coordinates (`unit=`; the default is Angstrom), converts it to Bohr,
//! and sets ζ = 1/radius². So ferric width [Bohr] == PySCF radius with
//! `unit="Bohr"`. The generator checks this on the PySCF side: coordinates
//! and radii handed over in Angstrom reproduce the Bohr run to ≤ 3e-14 Ha,
//! and a Bohr number misread as Angstrom moves the energy by 5.9e-4 to
//! 8.6e-3 Ha (`unit_convention_check` in each JSON).
//!
//! # Physics hypothesis vs artifact hypothesis
//!
//! * If ferric's embedding is right: energies agree at the integral/SCF
//!   floor (~1e-11 Ha for HF, second order in the density error), gradients
//!   and MM forces at the first-order floor (~1e-9 Ha/Bohr).
//! * If the field is dropped or never reaches the SCF (the vacuum-test
//!   failure mode): ferric returns the gas-phase answer. The reference shifts
//!   are 8.4e-4 to 1.6e-2 Ha, so every energy assertion fails by ≥ 7 orders
//!   above the bar. Each test asserts this FIRST (the vacuum block of
//!   `check_case`).
//! * If a charge is mis-scaled (a unit or sign slip in the charge, a missing
//!   factor in the charge-nuclear term): the ×1.01 control moves the energy by
//!   7.6e-7 (KS/PBE) to 2.4e-4 Ha, so ferric must match PySCF's ×1.01 energy AND miss
//!   the ×1 reference.
//! * If the smearing convention were off (ζ = 1/(2w²), width read as Å, width
//!   ignored): the width-swap and point-limit controls differ from the
//!   reference by ≥ 1.0e-4 Ha (measured by the generator, refused below
//!   1e-5), so a wrong convention fails every smeared test.
//! * If the harness is broken (geometry constant, wrong basis file, wrong
//!   reference file): the nuclear-repulsion and AO-count assertions fail
//!   first, before any SCF.
//!
//! # TOLERANCES
//!
//! Each bar is set from the measured maximum recorded on its const.
//!
//! # NEGATIVE CONTROLS (asserted inside every test)
//!
//! * vacuum: ferric's gas-phase energy and gradient must MISS the embedded
//!   reference by `MISS_FACTOR` × the bar;
//! * charges × 1.01: ferric must reproduce PySCF's ×1.01 energy and MISS the
//!   ×1 reference;
//! * smeared: ferric with each OTHER width, and ferric with point charges,
//!   must MISS the reference;
//! * KS: ferric with the OTHER functional must MISS the reference.
//! MUTATIONS to run by hand (each must turn a test red): drop
//! `external_potential` from `cfg` in [`scf`]; flip the sign of `mm_forces`;
//! pass `width * ANGSTROM_TO_BOHR` in [`build_system`].
//!
//! A missing reference JSON is a HARD failure (panic naming the path).

