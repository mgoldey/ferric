const ROW_DIR: &str = "testdata/reference/validation/qmmm";

/// HF total, gas-phase and embedding shift. Measured max 4.8e-12 Ha.
const TOL_E_HF: f64 = 5e-11;
/// HF QM gradient and MM force. Measured max 1.2e-10 / 4.4e-12 Ha/Bohr.
const TOL_G_HF: f64 = 1e-9;
const TOL_F_HF: f64 = 5e-11;
/// KS energies (exact J/K, matched grid). Measured max 4.1e-12 Ha. Must stay
/// below 1/10 of the PBE x1.01-charges gap (7.6e-7) for that control.
const TOL_E_KS: f64 = 1e-10;
/// KS QM gradient vs PySCF `grid_response=True`, and MM force. Measured max
/// 2.9e-9 / 1.8e-10 Ha/Bohr.
const TOL_G_KS: f64 = 3e-8;
const TOL_F_KS: f64 = 2e-9;
/// Smeared-width -> 0 anchor (ferric vs ferric). Measured 3.0e-12.
const TOL_ANCHOR_TINY_WIDTH: f64 = 1e-10;
const TOL_ENUC: f64 = 1e-9;
/// A control must miss the reference by this multiple of the bar it is
/// asserted against. The smallest control gap in the references is the PBE
/// ×1.01 case, 7.6e-7 Ha = 76 × `TOL_E_KS` (the 20 charges' first-order
/// electrostatic and second-order polarization terms nearly cancel in
/// dE/dq); every other gap is ≥ 2.3e-6 Ha. If `TOL_E_KS` is raised above
/// 7.6e-8 that control becomes unreachable and this test will say so.
const MISS_FACTOR: f64 = 10.0;

