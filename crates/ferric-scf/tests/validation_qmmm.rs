// ---------------------------------------------------------------------------
// "KS QM/MM": RKS, exact J/K, matched grid
// ---------------------------------------------------------------------------

fn check_ks(xc: &str, other: &str) {
    let stem = format!("ch3oh_q20_{xc}_def2-svp");
    let r = reference(&stem);
    assert_eq!(
        r["xc"].as_str().unwrap(),
        xc,
        "{stem}: reference functional"
    );
    // Functional swap: the SAME embedding with the other functional must miss
    // this reference (an ignored `xc` returns HF or a default functional).
    let sys = build_system(&r, 1.0, None);
    let qm = qm_part(&r, &sys, &stem);
    let swapped = scf(&qm, Some(&sys), Some(other), &format!("{stem}/{other}"));
    check_misses(
        &stem,
        &format!("{other} vs {xc} ref"),
        swapped.energy,
        num(&r, "/energy"),
        TOL_E_KS,
    );
    check_case(&stem, None, Some(xc), &KS);
}

