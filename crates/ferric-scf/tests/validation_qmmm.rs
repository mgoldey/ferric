fn check_close(ctx: &str, what: &str, got: f64, want: f64, tol: f64) {
    let d = (got - want).abs();
    eprintln!("{ctx}: {what:<22} ferric {got:+.12} ref {want:+.12} |d| {d:.2e} (tol {tol:.0e})");
    assert!(
        d < tol,
        "{ctx}: {what} {got:.12} vs reference {want:.12} (|d| {d:.2e} >= {tol:.0e})"
    );
}

fn check_misses(ctx: &str, what: &str, got: f64, want: f64, tol: f64) {
    let d = (got - want).abs();
    let bar = MISS_FACTOR * tol;
    eprintln!("{ctx}: CONTROL {what:<30} |d| {d:.2e} (must exceed {bar:.0e})");
    assert!(
        d > bar,
        "{ctx}: negative control '{what}' did NOT miss the reference (|d| {d:.2e} <= {bar:.0e}) \
         — the assertion cannot tell this arrangement from the real one"
    );
}

fn max_row_diff(a: &[[f64; 3]], b: &[[f64; 3]], sign_b: f64) -> (f64, usize, usize) {
    assert_eq!(a.len(), b.len());
    let mut worst = (0.0, 0, 0);
    for (i, (x, y)) in a.iter().zip(b.iter()).enumerate() {
        for k in 0..3 {
            let d = (x[k] - sign_b * y[k]).abs();
            if d > worst.0 {
                worst = (d, i, k);
            }
        }
    }
    worst
}

fn grad_rows(g: &Array2<f64>) -> Vec<[f64; 3]> {
    g.rows().into_iter().map(|r| [r[0], r[1], r[2]]).collect()
}

fn check_rows(ctx: &str, what: &str, got: &[[f64; 3]], want: &[[f64; 3]], sign: f64, tol: f64) {
    let (d, i, k) = max_row_diff(got, want, sign);
    eprintln!(
        "{ctx}: {what:<22} max|d| {d:.2e} at [{i}][{k}] over {} rows (tol {tol:.0e})",
        got.len()
    );
    assert!(
        d < tol,
        "{ctx}: {what}[{i}][{k}] ferric {} vs reference {} (|d| {d:.2e} >= {tol:.0e})",
        got[i][k],
        sign * want[i][k]
    );
}

struct Tols {
    e: f64,
    g: f64,
    f: f64,
}

const HF: Tols = Tols {
    e: TOL_E_HF,
    g: TOL_G_HF,
    f: TOL_F_HF,
};
const KS: Tols = Tols {
    e: TOL_E_KS,
    g: TOL_G_KS,
    f: TOL_F_KS,
};

/// One case: negative controls FIRST (vacuum, ×1.01), then the comparison.
/// Returns ferric's embedded energy.
fn check_case(file_stem: &str, width: Option<f64>, xc: Option<&str>, tol: &Tols) -> f64 {
    let r = reference(file_stem);
    let ctx = file_stem.to_string();
    let sys = build_system(&r, 1.0, width);
    let qm = qm_part(&r, &sys, &ctx);
    let n_mm = r["mm_charges"].as_array().unwrap().len();
    assert_eq!(
        sys.mm_charge_positions().len(),
        n_mm,
        "{ctx}: MM site count"
    );

    let e_ref = num(&r, "/energy");
    let e_gas_ref = num(&r, "/energy_gas_phase");
    // ferric's KS gradient includes the grid response (ferric-dft/src/gradient.rs),
    // so KS is compared against PySCF grid_response=True.
    let g_ref = rows3(
        &r,
        if xc.is_some() {
            "qm_gradient_grid_response"
        } else {
            "qm_gradient"
        },
    );
    let mm_grad_ref = rows3(&r, "mm_gradient");

    // --- gas phase + anti-vacuum control (FIRST: it licenses the rest) ----
    let gas = scf(&qm, None, xc, &format!("{ctx}/gas"));
    check_close(&ctx, "E gas phase", gas.energy, e_gas_ref, tol.e);
    check_misses(
        &ctx,
        "vacuum energy vs embedded ref",
        gas.energy,
        e_ref,
        tol.e,
    );
    let g_gas = grad_rows(&gradient(&qm, &gas, None, xc));
    let (dg_vac, _, _) = max_row_diff(&g_gas, &g_ref, 1.0);
    check_misses(&ctx, "vacuum gradient vs embedded ref", dg_vac, 0.0, tol.g);

    // --- embedded ----------------------------------------------------------
    let emb = scf(&qm, Some(&sys), xc, &ctx);
    check_close(&ctx, "E embedded", emb.energy, e_ref, tol.e);
    check_close(
        &ctx,
        "embedding shift",
        emb.energy - gas.energy,
        e_ref - e_gas_ref,
        tol.e,
    );
    let g = grad_rows(&gradient(&qm, &emb, Some(&sys), xc));
    check_rows(&ctx, "QM gradient", &g, &g_ref, 1.0, tol.g);
    let f = mm_forces(&sys, &qm.mol, &qm.prep, emb.density_total()).unwrap();
    // ferric returns the FORCE; the reference is dE/dR.
    check_rows(&ctx, "MM force", &f, &mm_grad_ref, -1.0, tol.f);

    // --- charges x 1.01: must match PySCF's x1.01 and miss the x1 ref ------
    let scale = num(&r, "/control_scaled_101/scale");
    let sys_s = build_system(&r, scale, width);
    let emb_s = scf(&qm, Some(&sys_s), xc, &format!("{ctx}/x{scale}"));
    check_close(
        &ctx,
        "E charges x1.01",
        emb_s.energy,
        num(&r, "/control_scaled_101/energy"),
        tol.e,
    );
    check_misses(&ctx, "charges x1.01 vs x1 ref", emb_s.energy, e_ref, tol.e);

    emb.energy
}

