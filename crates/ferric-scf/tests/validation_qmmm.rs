/// Exactness anchor: an MM region whose charges are all zero produces NO
/// potential (`None`, the literal gas-phase code path), and a smeared site
/// whose width goes to zero reproduces the point-charge energy. Both are
/// ferric-vs-ferric limits that a construction error would break before any
/// cross-code number is read.
#[test]
#[ignore = "validation: QM/MM"]
fn anchor_zero_charges_and_tiny_width() {
    let r = reference("h2o_q10_cc-pvdz");
    let ctx = "anchor/h2o_q10_cc-pvdz";
    let zero = build_system(&r, 0.0, None);
    assert!(
        zero.to_external_potential().is_none(),
        "{ctx}: all-zero MM charges must give no potential (the gas-phase path)"
    );
    let sys = build_system(&r, 1.0, None);
    let qm = qm_part(&r, &sys, ctx);
    let point = scf(&qm, Some(&sys), None, ctx);
    let tiny = build_system(&r, 1.0, Some(1e-4));
    let smeared = scf(&qm, Some(&tiny), None, &format!("{ctx}/w1e-4"));
    check_close(
        ctx,
        "E smeared w=1e-4 vs point",
        smeared.energy,
        point.energy,
        TOL_ANCHOR_TINY_WIDTH,
    );
}

